// БАЗОВЫЙ КЕГЛЬ ЭКРАНОВ, СВЁРСТАННЫХ В `rem` (answer.css и всё, что на нём стоит).
//
// Формула жила прямо в вёрстке:
//     html { font-size: clamp(13px, calc(1.42vh + 0.4vw + 4.8px), 18.5px); }
// `vh` — высота РАЗМЕТОЧНОЙ области. На Android она уменьшается вместе с выездом
// клавиатуры, и весь экран ужимается сам собой: замер 16.09.2026 в быстром словаре —
// 18,46 px → 13,91 px, то есть минус четверть, надпись «Быстрый словарь» с 14,4 до 10,9.
// На айфоне этого не видно: там окно страницы при клавиатуре не меняется.
//
// Лечение придумано не здесь: в интерактивах (answer/fitCard.js) ту же формулу давно
// считают в скрипте и обновляют ТОЛЬКО когда клавиатуры нет. Здесь она вынесена в общий
// файл, чтобы у неё был ОДИН источник: экранов, которые её применяют, стало два
// (интерактивы и быстрый словарь), а формула, скопированная в два места, разъезжается.
//
// Меряем `clientHeight`/`clientWidth` документа: это ровно то, что означают единицы
// `vh`/`vw`, поэтому без клавиатуры кегль выходит в точности прежний и вёрстка не едет.

const clampPx = (min, val, max) => Math.min(max, Math.max(min, val));

/**
 * @param {number} h высота разметочной области (documentElement.clientHeight)
 * @param {number} w ширина разметочной области (documentElement.clientWidth)
 * @returns {number|null} кегль в пикселях, либо null — если мерить ещё нечего
 */
export function computeBaseFontSize(h, w) {
  if (!(h > 200) || !(w > 0)) return null;
  // Порог тот же, что у медиазапроса в answer.css: ширина от 700 И высота от 560.
  const wide = w >= 700 && h >= 560;
  const px = wide
    ? clampPx(16, (0.9 * h + 0.7 * w) / 100 + 5, 26)
    : clampPx(13, (1.42 * h + 0.4 * w) / 100 + 4.8, 18.5);
  return Math.round(px * 100) / 100;
}

export default computeBaseFontSize;
