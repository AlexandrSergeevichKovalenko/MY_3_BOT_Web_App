// Хвост «из скольких игроков» для строки места на грамоте результата.
//
// 10.09.2026, решение владельца: число участников стоит В ТОЙ ЖЕ строке, что и место.
// Раньше «из N» жило на нижней строке рядом с числом верных ответов и читалось как
// одна невнятная фраза («из 1 · 12 верных (86%)»): человек не понимал, что за «из 1».
// Место без знаменателя — не результат, поэтому «из N игроков» держится при месте,
// а нижняя строка отдана только счёту ответов.
//
// Пустая строка — только когда участников правда ноль (ranking.total=0, никто не играл),
// то есть места тоже нет. Это не заглушка: знаменателя в этот момент не существует.
export function playersOf(total) {
  const n = Number(total) || 0;
  if (!n) return '';
  return `из ${n} ${pluralRu(n, 'игрока', 'игроков', 'игроков')}`;
}

// «41 слово» / «2 слова» / «5 слов» — тот же знаменатель, но про слова.
export function wordsOf(n) {
  const k = Number(n) || 0;
  return `${k} ${pluralRu(k, 'слово', 'слова', 'слов')}`;
}

// «12 верно ответивших» — знаменатель места в интерактиве дня: там соревнуются
// по скорости ТОЛЬКО те, кто ответил верно, поэтому знаменатель меньше числа
// сыгравших и обязан называться словами, иначе он читается как «всего игроков».
export function rightAnswerersOf(n) {
  const k = Number(n) || 0;
  return `${k} ${pluralRu(k, 'верно ответившего', 'верно ответивших', 'верно ответивших')}`;
}

// Русское склонение после числа: 1 игрока (из одного), 2–4 игроков, 5+ игроков.
// Форма «из» требует родительного падежа, поэтому единственное число тоже «игрока».
function pluralRu(n, one, few, many) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
