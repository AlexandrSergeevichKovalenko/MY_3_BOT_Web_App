// Опрос «а артикль ещё не появился?» УБРАН. Этот тест не даёт ему вернуться.
//
// Что стояло. Экран быстрого словаря, получив ответ без артикля, пять раз переспрашивал
// сервер с паузами 0,9 + 1,3 + 1,6 + 2,0 + 2,5 = до 8,3 секунды ожидания.
//
// Почему убрано — два замера 25.08.2026, оба на живых данных:
//
//   1. КОГО ОН ВООБЩЕ СПРАШИВАЛ. 299 реальных немецких однословных запросов из общего
//      пула, прогнаны через серверный код: 230 (77%) получают артикль сразу, опроса нет;
//      69 (23%) уходили в опрос. Из этих 69 — 29 за словами, у которых мы САМИ знаем
//      часть речи, и она не существительное: Danke (междометие), Genau (наречие),
//      Falsch (прилагательное), Alles (местоимение), Zum (предлог), Klingt (глагол).
//      У них артикля нет и быть не может.
//
//   2. МОГ ЛИ ОН ВООБЩЕ ДОЖДАТЬСЯ. По секундомеру на пяти словах, которые реально
//      уходили в опрос: фоновый добор занимает 28–30 секунд и НЕ НАХОДИТ артикль ни у
//      одного. Экран ждал 8,3. Разрыв не пограничный — подкручивать паузы бессмысленно.
//
// Сам сервер на этот опрос и не рассчитывал: у _schedule_quick_translate_article_fill
// в комментарии сказано «so the NEXT identical lookup shows der/die/das» — добор
// делается для СЛЕДУЮЩЕГО поиска, а не для текущего экрана.
//
// Незакрытое и КЕМ: добор кладёт артикль в память процесса; при росте числа процессов
// «следующий поиск» его не увидит. Передано agent/gsurface 25.08.2026 вместе со всей
// темой артикля — лечение там: класть в банк слов, а не в память.
import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/dictionary/DictionaryOverlay.jsx', import.meta.url), 'utf8');

test('ГЛАВНОЕ: экран больше не опрашивает сервер об артикле', () => {
  const calls = src.split('\n').filter(
    (line) => line.includes('/api/translate/quick/article') && !line.trimStart().startsWith('//'),
  );
  assert.deepEqual(calls, [], 'опрос вернулся — сначала перемерьте, см. шапку этого файла');
});

test('лестница пауз 900/1300/1600/2000/2500 не вернулась', () => {
  assert.equal(/\[\s*900\s*,\s*1300\s*,\s*1600\s*,\s*2000\s*,\s*2500\s*\]/.test(src), false);
});

test('вердикт замера остался в коде рядом с местом соблазна', () => {
  assert.ok(src.includes('ЗАМЕРЕНО 25.08.2026'), 'запись о замере исчезла — следующий агент померит это в шестой раз');
  assert.ok(src.includes('28–30 секунд'), 'число из замера исчезло');
});

test('артикль по-прежнему показывается, когда пришёл вместе с ответом', () => {
  assert.ok(src.includes("article: String(data?.article || '').trim()"),
    'артикль перестал забираться из ответа — это уже другая поломка');
});
