// Без сети словарь обязан искать в СВОИХ словах, а не только в базовом пакете.
//
// Что было. Владелец включил авиарежим и набрал «Змей горыныч» — фразу, которую сам
// переводил месяцем раньше. Ответ: «слово не найдено офлайн». Причина оказалась не в
// поиске и не в кеше: слова человека УЖЕ лежали на устройстве — их кладёт Библиотека
// (loadVocabLibrary → saveVocabBatch), и у getCachedVocab давно есть поиск по тексту.
// Офлайн-словарь просто туда не заглядывал: он знал только базовый пакет на 10 000
// частых немецких слов, где личных фраз нет и быть не может.
//
// Проверка статическая — по исходнику: IndexedDB в node нет, а разъехаться эта проводка
// может молча, без единой ошибки в сборке.
import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/App.jsx', import.meta.url), 'utf8');

const start = src.indexOf('const handleDictionaryBaseLookup = async');
assert.notEqual(start, -1, 'офлайн-обработчик словаря не найден');
const body = src.slice(start, start + 9000);

test('офлайн-поиск заглядывает в кеш моих слов', () => {
  assert.ok(body.includes('getCachedVocab('), 'офлайн-путь не обращается к кешу Библиотеки');
  assert.ok(/getCachedVocab\([^)]*search:/s.test(body),
    'getCachedVocab вызывается без search — тогда он вернёт не то слово, а просто первое');
});

test('свои слова ищутся РАНЬШЕ базового пакета', () => {
  const mine = body.indexOf('getCachedVocab(');
  const pack = body.indexOf('lookupOfflineBaseDictEntry(');
  assert.notEqual(pack, -1, 'обращение к базовому пакету исчезло');
  assert.ok(mine !== -1 && mine < pack,
    'базовый словарь спрашивается раньше своих слов — человек получит справочную строку вместо своей карточки');
});

test('без сети человек видит модалку в нашем стиле, а не красную плашку', () => {
  assert.ok(body.includes('showNoticeModal('), 'офлайн-путь не показывает модалку');
  assert.ok(!body.includes('Нет соединения и слово не найдено офлайн'),
    'вернулся старый технический текст');
});

test('в сообщениях нет отсылок к кнопкам, которых больше нет', () => {
  for (const ghost of ['⚡ Перевод', '📖 Офлайн', '🤖 AI']) {
    assert.ok(!body.includes(ghost),
      `сообщение зовёт нажать «${ghost}» — этой кнопки в интерфейсе нет с 08.08.2026`);
  }
});

test('тексты короткие: человек пришёл за переводом, а не читать', () => {
  // Ловим лекции вроде «Всё, что вы уже переводили, доступно и без сети» — длинную
  // фразу, которая ещё и врёт, если слово как раз недоступно.
  for (const m of body.matchAll(/message:\s*tr\(\s*'([^']{2,})'/g)) {
    assert.ok(m[1].length <= 90,
      `сообщение длиной ${m[1].length} знаков — это лекция, а не подсказка: «${m[1]}»`);
  }
});
