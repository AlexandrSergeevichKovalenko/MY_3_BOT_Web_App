"""Приёмка слов для анаграммы: ходовость и регистр. Решение владельца 13.09.2026.

Повод
─────
Владельцу 13.09.2026 пришла анаграмма с подсказкой «Закоулок» и словом `Inkelgasse`.
Такого слова нет: это «Winkelgasse», у которой отъели первую букву. По корпусу DWDS —
0 вхождений на 53,3 млрд слов. Карточка жила в банке с 21.08.2026 и ушла трём людям
(22.08, 04.09, 13.09). Саму статью словаря владелец уже чинил 02.09.2026
(`scripts/dict_units_fix_lowercase_nouns.py`, класс «обрубок»), но карточка — отдельная
копия, и до неё правка не дошла.

Замер всего банка 13.09.2026 (`scripts/anagram_bank_liveness_audit.py`, 163 карточки),
сырое число «35 редких» разложено на классы, потому что DWDS считает НАПИСАНИЕ, а не
слово:

    нет такого слова          1   Inkelgasse 0,0 — выдавалось людям
    испорчен регистр         16   Behaupten 102 против behaupten 47 477,
                                  Hervorrufen 33 против hervorrufen 8 184
    правда нечастые          18   Hühnerauge 192, Zigarettenstummel 299, домофон 277

Из 16 «испорченного регистра» три оказались НЕ дефектом: `das Aufstoßen` (отрыжка),
`das Abfangen` (перехват), `das Erschießen` (расстрел) — законные отглагольные
существительные, и подсказка у них тоже существительное. Поэтому регистр здесь не
угадывается по виду слова, а берётся из источника: часть речи записи и артикль в ней.

Что решил владелец 13.09.2026
─────────────────────────────
1. Порог ходовости — как у ребуса, 300 вхождений на миллиард (`rebus_word_gate.py`).
   Константа импортируется оттуда: два порога в двух файлах разъедутся.
2. Регистр чиним и слово оставляем («fix register and keep it»), а не выбрасываем.
3. Накопленное в банке НЕ трогаем — правило действует на пополнение. Ровно как решено
   по ребусу 01.09.2026. Исключение единственное и названо владельцем отдельно:
   `Inkelgasse` снимается, потому что это не редкое слово, а несуществующее.

Чего этот файл НЕ делает
────────────────────────
Он не придумывает написание. Если источник молчит о части речи — слово не берётся:
«не знаем» это не «годится». Это то же правило, что у ребуса про неответ DWDS.
"""
from __future__ import annotations

import logging
import re

from backend.rebus_word_gate import MIN_PER_BILLION  # один порог на два банка

logger = logging.getLogger(__name__)

# Части речи, которые в немецком пишутся со строчной. Это орфография языка, а не наша
# догадка о конкретном слове: догадка была бы «Behaupten похоже на глагол», а здесь
# часть речи приходит ИЗ ЗАПИСИ словаря.
LOWERCASE_POS = {"verb", "adjective", "adverb", "participle"}
UPPERCASE_POS = {"noun"}

_ARTICLE_RE = re.compile(r"^\s*(der|die|das)\s+", re.IGNORECASE)

# ┌─ ПРОВЕРЕНО 13.09.2026. НЕ ПОДНИМАТЬ ЭТО КАК НОВУЮ НАХОДКУ. ────────────────────────┐
# │ Мерили: слова банка анаграмм, начинающиеся со СТРОЧНОЙ буквы.                      │
# │ Сырое число: 31 карточка. Выглядит как «немецкие существительные без заглавной».   │
# │ Разложение по источнику (часть речи из bt_3_lex_units И из журнала запросов —      │
# │ оба источника совпали на всех 31): существительных среди них НЕТ ни одного.        │
# │ Это глаголы (anprobieren, beeinflussen, räuspern), прилагательные (großzügig,      │
# │ geräuschlos), наречия (fälschlicherweise) и причастия (ausgelaugt) — всё это в     │
# │ немецком пишется со строчной, и написано верно.                                    │
# │ Вердикт: ДЕФЕКТА НЕТ. Это и есть правильная работа правила ниже.                   │
# │ Перемерить: SELECT word FROM bt_3_anagram_cards WHERE word ~ '^[a-zäöüß]' и        │
# │ сверить часть речи с журналом. Находкой было бы слово, у которого источник         │
# │ говорит noun, — таких на 13.09.2026 ноль.                                          │
# └────────────────────────────────────────────────────────────────────────────────────┘


def source_part_of_speech(entry: dict) -> str:
    """Часть речи ИЗ ЗАПИСИ. Пустая строка — источник молчит, и это не повод гадать."""
    payload = entry.get("response_json")
    if not isinstance(payload, dict):
        payload = {}
    raw = entry.get("part_of_speech") or payload.get("part_of_speech") or ""
    return str(raw).strip().lower()


def _has_article(entry: dict) -> bool:
    """Стоит ли в записи артикль перед немецким словом.

    Артикль — прямое свидетельство существительного, и он важнее части речи: у
    `das Aufstoßen` часть речи записана «verb», но это отглагольное существительное,
    и заглавная у него ВЕРНА. Без этой проверки правка испортила бы три живых слова.
    """
    payload = entry.get("response_json")
    if not isinstance(payload, dict):
        payload = {}
    for field in ("translation_de", "word_de"):
        for source in (entry, payload):
            value = str(source.get(field) or "")
            if _ARTICLE_RE.match(value):
                return True
    return False


def spelling_by_source(word: str, entry: dict) -> tuple[str, str]:
    """(написание, причина отказа). Причина непустая ⇒ слово не берём.

    Три исхода:
      • источник молчит о части речи          → не берём;
      • существительное (или артикль в записи) → первая буква заглавная;
      • глагол/прилагательное/наречие          → первая буква строчная.
    """
    word = str(word or "").strip()
    if not word:
        return "", "пустое слово"
    pos = source_part_of_speech(entry)
    if not pos:
        return "", f"источник не знает части речи «{word}» — не берём, это не «годится»"
    if _has_article(entry) or pos in UPPERCASE_POS:
        return word[:1].upper() + word[1:], ""
    if pos in LOWERCASE_POS:
        return word[:1].lower() + word[1:], ""
    return "", f"часть речи «{pos}» не говорит о регистре «{word}»"


def judge_anagram_word(word: str, entry: dict, *, allow_network: bool = True) -> tuple[str, str]:
    """(годное написание, причина отказа). Годное написание пустое ⇒ слово не берём.

    Четыре исхода, и они РАЗНЫЕ:
      • источник не знает части речи      → не берём;
      • частота неизвестна (DWDS молчит)  → не берём, переспросим ночью;
      • частота ниже порога               → не берём, слово редкое;
      • иначе                             → берём, в правильном написании.
    """
    from backend.dwds_frequency import word_per_billion

    spelled, why = spelling_by_source(word, entry)
    if not spelled:
        return "", why

    # Частоту спрашиваем про ТО написание, которое уйдёт человеку: DWDS считает
    # написание, и «Behaupten» с «behaupten» у него два разных числа (102 и 47 477).
    ppb = word_per_billion(spelled, allow_network=allow_network)
    if ppb is None:
        return "", f"частота неизвестна — DWDS не ответил про «{spelled}», переспросим ночью"
    if ppb < MIN_PER_BILLION:
        return "", (f"слишком редкое: «{spelled}» встречается {ppb:.0f} раз на миллиард, "
                    f"порог {MIN_PER_BILLION:.0f}")
    return spelled, ""
