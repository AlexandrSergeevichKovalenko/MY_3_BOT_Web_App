"""ОДНА ДВЕРЬ, через которую входит любой текст, попадающий в словарь.

Зачем это появилось. Текст в словарь приходит из шести мест: окно быстрого словаря,
мобильное приложение, личный чат с ботом, «Ярлык» с айфона, читалка/видео и разовые
скрипты. У каждого места была СВОЯ чистка или не было никакой:

  окно и мобильное  — вычитка моделью, но только НА СОХРАНЕНИИ;
  бот               — ничего;
  «Ярлык»           — своя чистка (`_shortcut_normalize_unit_text`), про мусор из скриншотов;
  скрипты и сборки  — ничего вовсе (июльская массовая сборка так и завела единицу
                      «das Neugeborenes», которой в немецком языке нет).

Каждое новое место заводило свою чистку или обходилось без — дырка открывалась заново
с каждой задачей. Здесь она одна, и её проходят все.

Дверь работает в два слоя, и это разделение принципиальное:

  1. МЕХАНИКА (эта функция, `clean_text`) — бесплатно, мгновенно, всегда и везде.
     Невидимые знаки, неразрывные пробелы, переводы строк, нумерация из списка,
     типографские кавычки, повисшее тире, буквы-двойники из чужого алфавита. Это не
     язык, это грязь копипаста: правится однозначно, без модели, за микросекунды.
     Стоит на самом ДНЕ записи — мимо неё не пройдёт ни один скрипт.

  2. ЯЗЫК (отдельно, `backend_server`) — платно, поэтому с умом. Неверный артикль,
     падеж, опечатка. Это умеет только модель, и зовём мы её ТОЛЬКО там, где всё равно
     собираемся платить за разбор: если слово уже есть у нас в базе — оно верное по
     определению, и спрашивать не о чем.

Модуль намеренно НЕ ходит в базу и ничего не импортирует из сервера: его зовут и
скрипты, и бот, и веб.
"""
from __future__ import annotations

import re
import unicodedata

# ── Слой 1: механика ──────────────────────────────────────────────────────────────

# Нулевая ширина, метка порядка байтов, мягкий перенос. В тексте невидимы, но слово с
# ними не находится по своему же написанию: для базы это другая строка.
_INVISIBLE_RE = re.compile("[​‌‍⁠﻿­᠎]")

# Пробелы, которые пробелом не считаются при сравнении.
_ODD_SPACE_RE = re.compile("[  -    　\t\r\n\v\f]")

_MULTISPACE_RE = re.compile(r"\s{2,}")

# Маркер списка в начале — след копирования из списка. Тире отделено намеренно: оно
# обязано стоять с пробелом после себя, иначе мы съедаем содержание — в словаре живут
# окончания множественного числа «-e», «-n», «-en».
_LEADING_BULLET_RE = re.compile(r"^[\s•▪◦●■▸▹▶►*·‣⁃∙‧]+")
_LEADING_DASH_RE = re.compile(r"^[–—-]\s+")
# После снятой нумерации обязана идти БУКВА. Иначе мы съедаем дату: «10. 01. 24 товар
# прибыл на наш склад» превращалось в «24 товар прибыл на наш склад» (13 живых строк).
_LEADING_NUMBER_RE = re.compile(r"^\s*\d{1,3}\s*[.)]\s+(?=[^\W\d_])", re.UNICODE)
# Перечисление значений внутри строки: «1) белка; 2) круассан». Тогда первая цифра —
# не мусор от копипаста, а часть содержания, и снимать её нельзя.
_INNER_ENUMERATION_RE = re.compile(r"[;,]\s*\d{1,3}\s*[.)]\s")

# Повисший хвост: тире, двоеточие, точка с запятой. Знаки конца фразы . ! ? остаются.
_TRAILING_JUNK_RE = re.compile(r"[\s•·‣⁃∙–—\-:;,]+$")

# Пробел перед знаком препинания убираем, но многоточие не трогаем: «Was …» — это
# пауза, а не отбившийся знак, и «Was...» вместо «Was ...» уже правка текста, не грязи.
_SPACE_BEFORE_PUNCT_RE = re.compile(r"\s+(?![.]{2})([,.;:!?])(?![.])")

_QUOTE_PAIRS = (('"', '"'), ("'", "'"), ("«", "»"), ("“", "”"), ("„", "“"), ("‘", "’"))

_FANCY_TO_PLAIN = {
    "‘": "'", "’": "'", "‚": "'", "‛": "'",
    "″": '"', "′": "'", "‐": "-", "‑": "-",
}

# Буквы, которые в кириллице и латинице выглядят ОДИНАКОВО. Слово с такой буквой из
# чужого алфавита выглядит правильным, но не находится никогда — для базы это другая
# строка. Классика: «Hаus», где «а» русская.
_CYRILLIC_TO_LATIN = {
    "А": "A", "В": "B", "С": "C", "Е": "E", "Н": "H", "К": "K", "М": "M", "О": "O",
    "Р": "P", "Т": "T", "Х": "X", "У": "Y", "І": "I", "Ј": "J", "Ѕ": "S",
    "а": "a", "с": "c", "е": "e", "о": "o", "р": "p", "х": "x", "у": "y", "ѕ": "s",
    "і": "i", "ј": "j", "ԁ": "d", "һ": "h", "ѵ": "v", "м": "m", "к": "k", "т": "t",
    "в": "b", "н": "h",
}
_LATIN_TO_CYRILLIC = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М", "O": "О",
    "P": "Р", "T": "Т", "X": "Х", "Y": "У", "a": "а", "c": "с", "e": "е", "o": "о",
    "p": "р", "x": "х", "y": "у", "m": "м", "k": "к",
}

_LATIN_RE = re.compile(r"[A-Za-zÄÖÜäöüßẞ]")
_CYRILLIC_RE = re.compile(r"[А-Яа-яЁё]")
_TOKEN_SPLIT_RE = re.compile(r"(\s+)")

MAX_INTAKE_CHARS = 500


def _repair_homoglyphs_in_token(token: str) -> str:
    """Слово целиком написано одним алфавитом, кроме одной-двух букв-двойников из
    другого — эти буквы возвращаем в алфавит большинства.

    Осторожно и по СЛОВУ, а не по всей строке: «налог на выбросы CO2» и «die CO2 Abgabe»
    смешивают алфавиты законно, но внутри каждого слова алфавит один. Правим только то,
    у чего чужих букв меньшинство И все они — двойники; «Auto-Ремонт» не трогаем."""
    latin = len(_LATIN_RE.findall(token))
    cyrillic = len(_CYRILLIC_RE.findall(token))
    if not latin or not cyrillic:
        return token
    if latin >= cyrillic:
        table, alien_re = _CYRILLIC_TO_LATIN, _CYRILLIC_RE
    else:
        table, alien_re = _LATIN_TO_CYRILLIC, _LATIN_RE
    alien = alien_re.findall(token)
    if any(ch not in table for ch in alien):
        return token  # чужие буквы не двойники — это осознанно смешанное слово
    return "".join(table.get(ch, ch) for ch in token)


def repair_homoglyphs(text: str) -> str:
    return "".join(
        part if part.isspace() else _repair_homoglyphs_in_token(part)
        for part in _TOKEN_SPLIT_RE.split(str(text or ""))
    )


def clean_text(text) -> str:
    """Механическая чистка входа. Смысл не меняет НИКОГДА — только убирает грязь,
    из-за которой одно и то же слово перестаёт быть равно самому себе.

    Идемпотентна: повторный прогон ничего не меняет. Дёшева: чистая работа с памятью,
    без обращений к базе и к модели."""
    value = str(text or "")
    if not value:
        return ""
    # NFC — «ä» одной буквой, а не «a» + значок сверху. Иначе два одинаковых на вид
    # слова оказываются разными строками.
    value = unicodedata.normalize("NFC", value)
    value = _INVISIBLE_RE.sub("", value)
    value = _ODD_SPACE_RE.sub(" ", value)
    for fancy, plain in _FANCY_TO_PLAIN.items():
        value = value.replace(fancy, plain)
    value = value.replace("…", "...")
    value = _MULTISPACE_RE.sub(" ", value).strip()
    if not value:
        return ""
    # Обёртки снимаем слоями, пока строка меняется: «1. „das Haus“ —» отдаёт мусор с
    # обоих концов по очереди, и за один проход кавычки не снялись бы — сначала мешало
    # тире в конце. Цикл заодно делает чистку идемпотентной по построению.
    enumerated = bool(_INNER_ENUMERATION_RE.search(value))
    for _ in range(5):
        before = value
        if not enumerated:
            value = _LEADING_NUMBER_RE.sub("", value)
        value = _LEADING_BULLET_RE.sub("", value)
        value = _LEADING_DASH_RE.sub("", value)
        value = _TRAILING_JUNK_RE.sub("", value)
        for left, right in _QUOTE_PAIRS:
            if len(value) > 2 and value.startswith(left) and value.endswith(right):
                value = value[len(left):-len(right)].strip()
                break
        if value == before:
            break
    # Незакрытую скобку НЕ трогаем. Проверено на живой базе: обрезать хвост значит
    # потерять содержание («партнёр (в паре, романтических отношениях» → «партнёр»),
    # а дописать закрывающую — выдумать за человека. Таких строк три на всю базу.
    value = _SPACE_BEFORE_PUNCT_RE.sub(r"\1", value)
    value = _TRAILING_JUNK_RE.sub("", value)
    value = repair_homoglyphs(value)
    value = _MULTISPACE_RE.sub(" ", value).strip()
    return value[:MAX_INTAKE_CHARS].strip()


def has_latin(text) -> bool:
    return bool(_LATIN_RE.search(str(text or "")))


def has_cyrillic(text) -> bool:
    return bool(_CYRILLIC_RE.search(str(text or "")))


def clean_all(*values) -> tuple:
    """Чистка нескольких полей разом — чтобы у двери не забыли ни одно.

    Регистр артикля правится здесь же и во ВСЕХ полях без разбора, какое из них
    немецкое: правило срабатывает только на «Артикль + одно немецкое слово», и в
    русский текст оно попасть не может по построению."""
    return tuple(
        lower_leading_article(clean_text(v)) if isinstance(v, str) or v is None else v
        for v in values
    )


# ── Слой 2: когда вообще стоит спрашивать модель ──────────────────────────────────

# Одна буква / цифра / знак — спрашивать нечего.
_HAS_LETTER_RE = re.compile(r"[^\W\d_]", re.UNICODE)


def worth_language_check(text: str, lang: str) -> bool:
    """Стоит ли тратить обращение к модели на проверку правописания.

    Правило простое и денежное: проверяем ТОЛЬКО то, за что мы всё равно собираемся
    платить разбором. Если слово уже лежит у нас в базе — оно верное, спрашивать не о
    чем (это решает вызывающая сторона, здесь — дешёвые отсечки)."""
    value = str(text or "").strip()
    if not value or len(value) > 200:
        return False
    if str(lang or "").lower() not in ("de", "ru"):
        return False
    if not _HAS_LETTER_RE.search(value):
        return False
    # Ссылка, почта, номер — не язык.
    if "://" in value or "@" in value or value.replace(" ", "").isdigit():
        return False
    return True


# Заголовок вида «Артикль + одно слово». Предложение сюда не попадает намеренно:
# «Die Kosten waren höher als erwartet.» начинается с большой буквы ЗАКОННО.
_ARTICLE_HEADWORD_RE = re.compile(
    r"^(Der|Die|Das)(\s+)([A-ZÄÖÜ][A-Za-zÄÖÜäöüß-]*)$"
)


def lower_leading_article(text) -> str:
    """«Die Enkelin» → «die Enkelin». Смысл не меняется, меняется только регистр.

    В немецком артикль пишется со строчной; с заглавной он стоит, только когда
    открывает предложение. В словарной карточке он предложение не открывает, и
    «Die Kundgebung» читается как обрывок фразы, а не как словарная запись.

    Замер 11.08.2026: в общем пуле накопилось 1 384 таких заголовка. Их починили
    разом, но без этого правила на входе они начали бы копиться заново — модель
    возвращает заголовок с большой буквы регулярно.

    Трогаем ТОЛЬКО «артикль + ОДНО слово». Всё остальное возвращаем как есть:
    у предложения большая буква законная, и опустить её значит сломать текст."""
    value = str(text or "").strip()
    match = _ARTICLE_HEADWORD_RE.match(value)
    if not match:
        return value
    return f"{match.group(1).lower()}{match.group(2)}{match.group(3)}"
