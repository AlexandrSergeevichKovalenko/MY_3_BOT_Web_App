# -*- coding: utf-8 -*-
"""Статьи, где часть речи спорит с родом: разбор по справочникам, остальное — владельцу.

Повод
─────
13.09.2026, по дороге к анаграмме. В слое статей нашлись записи вида «прилагательное
с родом der» и «глагол с родом die». Род в немецком бывает ТОЛЬКО у существительного,
поэтому такая запись противоречит сама себе: одно из двух полей неверно, и по ней
нельзя ни показать артикль, ни решить регистр.

Замер 13.09.2026: 21 запись. Из них ВИДНО на экране 8 — немецкое существительное
написано со строчной буквы и помечено прилагательным, поэтому формула показа заглавную
не поднимает (она верит пометке). Человек читает «ruhestände», «schiffwrack»,
«zEITSCHRIFT»: 36 личных карточек. В немецком существительное со строчной — ошибка
всегда, а это языковое приложение.

Почему одним правилом чинить НЕЛЬЗЯ
───────────────────────────────────
Соблазн: «род есть — значит существительное, поднимай заглавную». Проверка 13.09.2026
на живых данных показала цену такой правки:

    hart    справочник склонений отвечает «der» — но это про фамилию Hart,
            а у нас прилагательное «твёрдый». Заглавная испортила бы слово.
    Läster  справочник отвечает «die» — а у нас «клеветник», то есть der Lästerer.
            Правка закрепила бы обрубок.

Поэтому часть речи берётся у DWDS — академического словаря, который отвечает ТОЧНЫМ
совпадением заголовка и не подсовывает похожее (`backend/german_reference_dwds.py`).
Он же честно молчит про обрубки и опечатки, и это молчание — сигнал, а не помеха.

Три исхода, и они разные
────────────────────────
    DWDS: «Substantiv»          → это существительное: часть речи и регистр чиним.
    DWDS: «Verb»/«Adjektiv»/…   → это НЕ существительное: снимаем род, он невозможен.
    DWDS слова не знает          → слово испорчено (обрубок, опечатка, множественное
                                   число, старая орфография) — решает ВЛАДЕЛЕЦ. Уходит
                                   в очередь жалоб: ночной судья предложит вариант,
                                   владелец получит пачку с кнопками.
    DWDS не ответил              → не решаем ничего, спросим в следующий раз.
"""
from __future__ import annotations

import logging

logger = logging.getLogger(__name__)

# Разметка DWDS. «Substantiv» приходит и с уточнением, поэтому сравниваем по началу.
СУЩЕСТВИТЕЛЬНОЕ = "Substantiv"
НЕ_СУЩЕСТВИТЕЛЬНОЕ = ("Verb", "Adjektiv", "Adverb", "Partizip", "Partikel",
                      "Konjunktion", "Präposition", "Pronomen", "Interjektion",
                      "Numerale", "Artikel")

РЕШЕНО_СУЩЕСТВИТЕЛЬНОЕ = "существительное"
РЕШЕНО_НЕ_СУЩЕСТВИТЕЛЬНОЕ = "не существительное"
ВЛАДЕЛЬЦУ = "владельцу"
НЕ_СПРОСИЛИ = "не спросили"


def варианты_написания(display: str) -> list[str]:
    """Написания, о которых имеет смысл спросить словарь.

    Спрашиваем и как лежит, и со строчной, и с заглавной: в базе встречаются и
    «ruhestände», и «Jahrelang», и «zEITSCHRIFT» — капс из выделенного текста.
    Порядок важен: сначала как лежит, потом приведённые формы.
    """
    текст = str(display or "").strip()
    if not текст:
        return []
    буквы = [c for c in текст if c.isalpha()]
    капс = len(буквы) > 1 and all(c.isupper() for c in буквы[1:])
    основа = текст[:1] + текст[1:].lower() if капс else текст
    варианты = [текст, основа[:1].lower() + основа[1:], основа[:1].upper() + основа[1:]]
    out: list[str] = []
    for v in варианты:
        if v and v not in out:
            out.append(v)
    return out


def разобрать(display: str, спросить_dwds) -> tuple[str, str, str]:
    """(решение, написание_по_словарю, ответ_словаря).

    `спросить_dwds` — функция «слово → часть речи | '' | None», чтобы этот модуль
    оставался проверяемым без сети (тот же приём, что у остальных судей проекта).
    """
    молчал = False
    for вариант in варианты_написания(display):
        ответ = спросить_dwds(вариант)
        if ответ is None:
            молчал = True
            continue
        if not ответ:
            continue
        if ответ.startswith(СУЩЕСТВИТЕЛЬНОЕ):
            return РЕШЕНО_СУЩЕСТВИТЕЛЬНОЕ, вариант, ответ
        if ответ.startswith(НЕ_СУЩЕСТВИТЕЛЬНОЕ):
            return РЕШЕНО_НЕ_СУЩЕСТВИТЕЛЬНОЕ, вариант, ответ
    if молчал:
        return НЕ_СПРОСИЛИ, "", ""
    return ВЛАДЕЛЬЦУ, "", ""


# ── ночной проход ────────────────────────────────────────────────────────────────────
# Класс не исторический: из 21 записи четыре появились за две недели до замера
# (Läster 31.08, gottlos 02.09, brummen 04.09, übersteigen 09.09). Разовый скрипт такой
# класс не закрывает — он закрывает только сегодняшний день. Поэтому разбор идёт каждую
# ночь, сам, и молчание DWDS не теряется: слово просто дождётся следующей ночи.
ВЛАДЕЛЕЦ_ПО_УМОЛЧАНИЮ = 117649764

# Сколько статей разбираем за ночь. Каждая — до трёх запросов к DWDS; двадцати хватает,
# чтобы за неделю пройти любой разумный накопленный хвост, и мало, чтобы ночь встала.
НОЧНОЙ_ПОТОЛОК = 20


def разобрать_противоречия(*, limit: int = НОЧНОЙ_ПОТОЛОК,
                           владелец: int = ВЛАДЕЛЕЦ_ПО_УМОЛЧАНИЮ,
                           спросить=None) -> dict:
    """Разобрать статьи, где часть речи спорит с родом. Возвращает счётчики.

    Ничего не угадывает: часть речи берётся у DWDS, род существительного — из
    справочника склонений. Чего словарь не знает — уходит владельцу с кнопками.

    ТРИ ФАЗЫ, и это не украшение. Первый вариант держал одно соединение с базой
    открытым, пока ходил в DWDS (до трёх запросов с паузами на слово) — прогон
    13.09.2026 упал на «SSL connection has been closed unexpectedly» на девятом
    слове. Соединение нельзя держать через сетевое ожидание: ни здесь, ни ночью,
    где рядом работают люди.
    """
    from backend.card_complaints import add_complaint
    from backend.database import get_db_connection_context, spread_correction_everywhere
    from backend.lex_units import retitle_unit
    from backend.noun_declension_reference import article_from_declension_reference

    if спросить is None:
        from backend.german_reference_dwds import dwds_pos as спросить

    итог = {"существительными": 0, "снят род": 0, "владельцу": 0, "отложено": 0}

    # ── фаза 1: прочитать список (короткое соединение) ────────────────────────────
    with get_db_connection_context() as conn:
        with conn.cursor() as cur:
            # Записи, уже лежащие у владельца, НЕ берём повторно. Без этого каждая
            # ночь переоткрывала бы его же заявку: `add_complaint` при повторе сбрасывает
            # статус и стирает вердикт судьи — то есть ночь за ночью стирала бы готовый
            # ответ модели и платила за него заново, а владелец видел бы одно и то же
            # слово как новое. Поймано прогоном 13.09.2026 на втором заходе.
            cur.execute("""
                SELECT u.id, u.display, u.pos, u.gender FROM bt_3_lex_units u
                WHERE u.lang = 'de' AND u.pos IN ('verb','adjective','adverb')
                  AND u.gender IS NOT NULL
                  AND NOT EXISTS (SELECT 1 FROM bt_3_card_complaints c
                                   WHERE c.unit_id = u.id AND c.status <> 'решена')
                ORDER BY u.updated_at NULLS FIRST
                LIMIT %s
            """, (int(limit),))
            статьи = cur.fetchall() or []

    # ── фаза 2: спросить словари (без соединения с базой) ─────────────────────────
    решения = []
    for uid, display, pos, gender in статьи:
        решение, написание, ответ = разобрать(display, спросить)
        род = источник_рода = None
        if решение == РЕШЕНО_СУЩЕСТВИТЕЛЬНОЕ:
            заглавная = написание[:1].upper() + написание[1:]
            род, источник_рода = article_from_declension_reference(заглавная)
            написание = заглавная
        решения.append((uid, display, pos, gender, решение, написание, ответ,
                        род, источник_рода))

    # ── фаза 3: записать (короткое соединение) ────────────────────────────────────
    владельцу_список = []
    with get_db_connection_context() as conn:
        with conn.cursor() as cur:
            for (uid, display, pos, gender, решение, написание, ответ,
                 род, источник_рода) in решения:
                if решение == НЕ_СПРОСИЛИ:
                    итог["отложено"] += 1
                    continue

                if решение == РЕШЕНО_СУЩЕСТВИТЕЛЬНОЕ:
                    cur.execute(
                        "UPDATE bt_3_lex_units SET pos = %s, pos_source = %s, "
                        "gender = COALESCE(%s, gender), "
                        "gender_source = CASE WHEN %s IS NULL THEN gender_source ELSE %s END, "
                        "updated_at = NOW() WHERE id = %s",
                        ("noun", f"DWDS: {ответ}", род, род, источник_рода, int(uid)))
                    if написание != display:
                        retitle_unit(cur, int(uid), написание)
                        spread_correction_everywhere(cur, unit_id=int(uid),
                                                     old_text=display, new_text=написание)
                    итог["существительными"] += 1
                    continue

                if решение == РЕШЕНО_НЕ_СУЩЕСТВИТЕЛЬНОЕ:
                    # Род у несуществительного невозможен. Снимаем именно его: это он
                    # делал запись похожей на существительное для всех, кто её читает.
                    cur.execute(
                        "UPDATE bt_3_lex_units SET gender = NULL, gender_source = NULL, "
                        "pos_source = %s, updated_at = NOW() WHERE id = %s",
                        (f"DWDS: {ответ}", int(uid)))
                    if написание and написание != display:
                        retitle_unit(cur, int(uid), написание)
                        spread_correction_everywhere(cur, unit_id=int(uid),
                                                     old_text=display, new_text=написание)
                    итог["снят род"] += 1
                    continue

                владельцу_список.append((int(uid), str(display), str(pos), str(gender)))

    # Заявка владельцу заводится своим соединением — держать чужую транзакцию открытой
    # ради неё незачем, а её собственная дверь уже умеет всё сама.
    for uid, display, pos, gender in владельцу_список:
        add_complaint(
            user_id=int(владелец), word=display, unit_id=uid,
            note=(f"системная проверка: часть речи «{pos}» спорит с родом «{gender}». "
                  f"Род бывает только у существительного. DWDS этого написания не "
                  f"знает — похоже на обрубок, опечатку, множественное число или "
                  f"старую орфографию."))
        итог["владельцу"] += 1

    logger.info("разбор противоречий часть речи/род: %s", итог)
    return итог
