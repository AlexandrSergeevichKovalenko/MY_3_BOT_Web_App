# -*- coding: utf-8 -*-
"""Однокоренная тавтология в русском переводе примера.

ПОВОД. Владелец 30.08.2026 прислал с экрана сравнения «anbieten ↔ unterbreiten»:

    Die Firma unterbreitete ein neues Angebot.
    Компания предложила новое предложение.          ← так по-русски не говорят

    Wir möchten Ihnen ein Angebot anbieten.
    Мы хотели бы предложить вам предложение.        ← и так тоже

Немецкий в обоих примерах верный. Ломается русская сторона: модель переводит слово
в слово («unterbreiten» → «предлагать», «Angebot» → «предложение») и не замечает, что
по-русски вышел плеоназм. Правильно — «сделала новое предложение», «сделать вам
предложение». Ученик читает русскую строку как образец смысла, и кривой русский учит
его неверно понимать немецкую фразу.

ЧТО ИМЕННО ЛОВИМ — узкий класс, а не «повтор корня вообще»: глагол и однокоренное ему
ОТГЛАГОЛЬНОЕ существительное, стоящее ПОСЛЕ него, в пределах четырёх слов И внутри
одного куска фразы (до ближайшего знака препинания). Обе границы держат класс:
  • порядок — «Читатель читает книгу» законна, там существительное стоит ПЕРЕД глаголом
    и называет деятеля, а не действие;
  • знак препинания — «Он работает в компании, где работа тяжёлая» и «Он предложил ей
    руку, и она приняла его предложение» тоже законны: за запятой другая мысль.

ИСТОЧНИК: pymorphy3 — словарный морфологический разбор русского (MIT, офлайн). Тот же,
что уже отвечает за часть речи в `backend/russian_part_of_speech.py`. Своей морфологии
мы не сочиняем: части речи и леммы берутся у него.

ЭТО СТОРОЖ, А НЕ СУДЬЯ. Он говорит «здесь подозрительно», и только. Ничего не режет и
ничего не переписывает: решение — за моделью, которую просят перевести заново, и за
владельцем. Так ложное срабатывание («открыл открытку») стоит одного лишнего вопроса,
а не потерянного примера.
"""
import logging
import re

logger = logging.getLogger(__name__)

_WORD = re.compile(r"[А-Яа-яЁё]+")

# Насколько далеко друг от друга могут стоять глагол и его отглагольное имя, чтобы это
# читалось как ОДНА конструкция: «предложила новое предложение» — через слово,
# «удостоверять личность с помощью удостоверения» — через три служебных.
#
# ┌─ ПОДНЯТО с 3 до 4 — 30.08.2026, по итогу первой же уборки. ──────────────────┐
# │ Модель переписала «удостоверять личность удостоверением» в «удостоверять     │
# │ личность с помощью удостоверения» — плеоназм остался, а сторож его пропустил │
# │ и принял правку. Расстояние там ровно 4.                                     │
# └──────────────────────────────────────────────────────────────────────────────┘
_MAX_DISTANCE = 4

# Ищем ВНУТРИ одного куска фразы. Граница — знак препинания: за ней начинается другая
# мысль, и однокоренное слово там законно. «Он работает в компании, где работа тяжёлая»
# и «Он предложил ей руку, и она приняла его предложение» — нормальный русский, и
# резать их нельзя; без этой границы правило с расстоянием 4 пометило бы первую фразу.
_CLAUSE_SPLIT = re.compile(r"[,.;:!?…—–-]+")

# Общая часть лемм, при которой слова считаются однокоренными. Порог не «на глаз»:
# «предложить»/«предложение» дают «предлож» (7), «предлагать»/«предложение» — «предл»
# (5) на чередовании, а посторонние пары вроде «писать»/«письмо» (3) и «начать»/
# «начало» (4) до порога не дотягивают и под правило не попадают.
_MIN_COMMON = 5
_MIN_LEMMA = 6


def _clauses(text: str) -> list[str]:
    """Куски фразы между знаками препинания — внутри них и ищем повтор."""
    return [part for part in _CLAUSE_SPLIT.split(str(text or "")) if part.strip()]


def _analyze(text: str):
    """Слова куска: (позиция, лемма, часть речи pymorphy3). [] — разбор недоступен."""
    from backend.russian_part_of_speech import _get_analyzer
    analyzer = _get_analyzer()
    if analyzer is None:
        return []
    out = []
    for index, match in enumerate(_WORD.finditer(str(text or ""))):
        word = match.group(0)
        try:
            parses = analyzer.parse(word)
        except Exception:
            logger.warning("тавтология: разбор упал на «%s»", word, exc_info=True)
            continue
        if not parses:
            continue
        top = parses[0]
        out.append((index, str(top.normal_form or "").lower(), str(top.tag.POS or "")))
    return out


def _common_prefix(first: str, second: str) -> int:
    size = 0
    for a, b in zip(first, second):
        if a != b:
            break
        size += 1
    return size


def tautology_pairs(text: str) -> list[tuple[str, str]]:
    """Пары «глагол → однокоренное существительное после него». Пусто — чисто.

    Разбор недоступен (pymorphy3 не установлен) — возвращаем пусто. Это «не знаем»,
    а не «чисто»: страж просто молчит и никого не помечает.
    """
    found: list[tuple[str, str]] = []
    for clause in _clauses(text):
        found.extend(_pairs_in_clause(clause))
    return found


def _pairs_in_clause(clause: str) -> list[tuple[str, str]]:
    words = _analyze(clause)
    found: list[tuple[str, str]] = []
    for position, lemma, pos in words:
        if pos not in ("VERB", "INFN", "GRND", "PRTF", "PRTS") or len(lemma) < _MIN_LEMMA:
            continue
        for other_position, other_lemma, other_pos in words:
            if other_pos != "NOUN" or len(other_lemma) < _MIN_LEMMA:
                continue
            # Существительное стоит ПОСЛЕ глагола и рядом с ним.
            if not (0 < other_position - position <= _MAX_DISTANCE):
                continue
            if _common_prefix(lemma, other_lemma) >= _MIN_COMMON:
                found.append((lemma, other_lemma))
    return found


def looks_tautological(text: str) -> bool:
    """Короткий ответ для стража на входе."""
    return bool(tautology_pairs(text))
