"""Сторож буквальных переводов: «предложила предложение» вместо «сделала предложение».

Владелец 30.08.2026 прислал два перевода с экрана сравнения «anbieten ↔ unterbreiten»:

    Die Firma unterbreitete ein neues Angebot. → Компания предложила новое предложение.
    Wir möchten Ihnen ein Angebot anbieten.    → Мы хотели бы предложить вам предложение.

Немецкий в обоих верный. Ломается русская сторона: модель перевела слово в слово, а
по-русски вышел плеоназм. Ученик читает русскую строку как образец смысла — и учится
понимать саму немецкую фразу неверно.

Правило нарочно УЗКОЕ: глагол и однокоренное отглагольное существительное ПОСЛЕ него.
Порядок слов держит границу класса: «Читатель читает книгу» — законная фраза, там
существительное стоит перед глаголом и называет деятеля, а не действие. Ошибись правило
в другую сторону — и оно резало бы нормальные примеры.

Сторож НИЧЕГО НЕ РЕЖЕТ: он считает (reason «tautology» в счётчике «не смогли») и
показывает уборке, что переписать. Поэтому ложное срабатывание стоит одного лишнего
вопроса модели, а не потерянного примера.
"""
import pytest

from backend import backend_server
from backend.russian_tautology import looks_tautological, tautology_pairs


@pytest.mark.parametrize("phrase", [
    # Ровно то, что было на экране.
    "Компания предложила новое предложение.",
    "Мы хотели бы предложить вам предложение.",
    "Он работает над работой.",
    # ┌─ ПОЙМАНО 30.08.2026 ПЕРВОЙ ЖЕ УБОРКОЙ. ────────────────────────────────┐
    # │ Модель переписала «удостоверять личность удостоверением» вот в это —   │
    # │ плеоназм остался, а сторож с расстоянием 3 его пропустил и принял      │
    # │ правку. Отсюда и предел 4: между словами тут три служебных.            │
    # └────────────────────────────────────────────────────────────────────────┘
    "удостоверять личность с помощью удостоверения",
])
def test_pleonasm_is_flagged(phrase):
    assert looks_tautological(phrase), phrase


@pytest.mark.parametrize("phrase", [
    # Правильные переводы тех же немецких фраз — их трогать нельзя.
    "Компания сделала новое предложение.",
    "Мы хотели бы сделать вам предложение.",
    # Существительное ПЕРЕД глаголом называет деятеля: это нормальный русский.
    "Читатель читает книгу.",
    "Машинист остановил машину.",
    # За знаком препинания начинается другая мысль — однокоренное слово там законно.
    # Без этой границы предел 4 пометил бы первую фразу.
    "Он работает в компании, где работа тяжёлая",
    "Он предложил ей руку, и она приняла его предложение",
    # То, чем уборка 30.08.2026 заменила кривые переводы: это уже чистый русский.
    "подтверждать личность с помощью удостоверения.",
    "удостоверять личность с помощью документа",
    "предъявить удостоверение личности",
    "Мы хотели бы вам что-то предложить.",
    # Остальные примеры с того же экрана.
    "Она предложила ему кофе.",
    "Дом выставлен на продажу.",
    "Билеты предлагаются по специальной цене.",
    "Она предлагает поддержку своим друзьям.",
])
def test_clean_translations_are_left_alone(phrase):
    assert not looks_tautological(phrase), f"{phrase} → {tautology_pairs(phrase)}"


def test_pair_names_both_words():
    """Отчёт должен говорить, ЧТО именно повторилось, а не «что-то не так»."""
    assert tautology_pairs("Компания предложила новое предложение.") == [
        ("предложить", "предложение")]


def test_guard_reads_every_place_the_screen_shows():
    """Перевод приходит из четырёх блоков, и человек видит их вместе — проверяем все."""
    diff = {
        "examples": [
            {"word": "unterbreiten", "de": "Wir möchten Ihnen ein Angebot unterbreiten.",
             "translation": "Мы хотели бы сделать вам предложение.",
             "contrast": {"type": "possible_but_different_register",
                          "de": "Wir möchten Ihnen ein Angebot anbieten.",
                          "translation": "Мы хотели бы предложить вам предложение."}},
        ],
        "constructions": [
            {"word": "unterbreiten", "example_de": "Die Firma unterbreitete ein neues Angebot.",
             "example_ru": "Компания предложила новое предложение."},
            {"word": "anbieten", "example_de": "Sie bot ihm einen Kaffee an.",
             "example_ru": "Она предложила ему кофе."},
        ],
        "collocations": [{"word": "anbieten", "phrase": "Hilfe anbieten",
                          "translation": "предложить помощь"}],
    }
    found = backend_server._word_diff_tautologies(diff)
    assert len(found) == 2, found
    assert any(line.startswith("контраст:") for line in found)
    assert any(line.startswith("конструкция:") for line in found)


def test_clean_diff_reports_nothing():
    diff = {
        "examples": [{"word": "unterbreiten", "de": "…",
                      "translation": "Мы хотели бы сделать вам предложение."}],
        "constructions": [{"word": "anbieten", "example_de": "…",
                           "example_ru": "Она предложила ему кофе."}],
    }
    assert backend_server._word_diff_tautologies(diff) == []
