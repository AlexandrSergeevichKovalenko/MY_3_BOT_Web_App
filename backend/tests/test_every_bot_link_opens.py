# -*- coding: utf-8 -*-
"""КАЖДАЯ КНОПКА БОТА ОБЯЗАНА ОТКРЫВАТЬСЯ. Дверь без ключа — это сломанная кнопка.

ПОВОД, 04.09.2026. Владельцу пришло сообщение «Карточки словаря: примеры и перевод» с
кнопкой «📗 Разобрать карточки (100)». Нажал — «Ungültiger Link».

Разбор: кнопка слала код `ans_frvp_0`, экран для него был написан (`kind === 'frvp'` в
AnswerOverlay), но в РАЗБОР ссылки код никто не вписал — регулярка его не знала, и
`parsed` выходил пустым. Дверь построили 26.08.2026 и с тех пор сообщение уходило по
вторникам и пятницам с мёртвой кнопкой.

Прежний тест на эту дверь проверял, что БОТ шлёт `ans_frvp_0`, — и был зелёным. Это тот
самый случай, который в проекте уже назван словами: «проверка „что записано“ — не
проверка „что видно“». Здесь сверяются ДВА списка: коды, которые бот отправляет
кнопкой, и коды, которые умеет открыть приложение.
"""
import pathlib
import re
import unittest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]


def _коды_в_кнопках_бота() -> set[str]:
    """Коды `ans_<вид>_…`, которые бот реально отправляет кнопкой."""
    коды: set[str] = set()
    файлы = [КОРЕНЬ / "bot_3.py"] + sorted((КОРЕНЬ / "backend").glob("*.py"))
    for путь in файлы:
        src = путь.read_text(encoding="utf-8", errors="ignore")
        # Только литералы: `f"ans_{kind}_…"` подставляет вид на ходу, и его проверяет
        # тот код, который этот вид выбирает.
        коды.update(re.findall(r'get_webapp_deeplink\(\s*f?"ans_([a-z]+)_', src))
    return коды


def _коды_которые_умеет_открыть() -> set[str]:
    jsx = (КОРЕНЬ / "frontend/src/answer/AnswerOverlay.jsx").read_text(encoding="utf-8")
    умеет = set()
    общая = re.search(r"\^ans_\(([a-z|]+)\)_", jsx)
    if общая:
        умеет.update(общая.group(1).split("|"))
    # У «gv» свой разбор: хвост там не число, а ключ темы.
    умеет.update(re.findall(r"\^ans_([a-z]+)_\(\[a-z_\]", jsx))
    return умеет


class КаждаяКнопкаОткрываетсяTests(unittest.TestCase):

    def test_every_bot_link_opens(self):
        мёртвые = sorted(_коды_в_кнопках_бота() - _коды_которые_умеет_открыть())
        self.assertEqual(
            мёртвые, [],
            f"бот шлёт кнопки, которые приложение не умеет открыть: {мёртвые}. "
            f"Впиши код в разбор ссылки (parseStartParam, AnswerOverlay.jsx) — "
            f"ДЛИННЫЕ коды ставь ПЕРЕД короткими.")

    def test_the_cards_door_specifically(self):
        """Та самая дверь, ради которой тест и написан."""
        self.assertIn("frvp", _коды_которые_умеет_открыть())
        self.assertIn("frvp", _коды_в_кнопках_бота())

    def test_each_code_parses_to_itself(self):
        """Ссылку разбираем НАСТОЯЩЕЙ регуляркой экрана, а не рассуждением о ней.

        ┌─ ПРОВЕРЕНО 04.09.2026. НЕ ПОДНИМАТЬ КАК НОВУЮ НАХОДКУ. ────────────────────┐
        │ Первая версия этого теста требовала, чтобы длинный код стоял ПЕРЕД похожим │
        │ коротким («frvp» перед «frv»), — и падала на «rb»/«rbv», которые живут так │
        │ давно и работают. Догадка была неверной: у чередования есть возврат, а `$`  │
        │ требует совпадения целиком, поэтому движок доходит до нужной ветки сам.    │
        │ Проверять надо не порядок, а результат разбора — им и проверяем.           │
        └────────────────────────────────────────────────────────────────────────────┘
        """
        jsx = (КОРЕНЬ / "frontend/src/answer/AnswerOverlay.jsx").read_text(encoding="utf-8")
        шаблон = re.search(r"/\^ans_\(([a-z|]+)\)_\(\\d\+\)\$/", jsx)
        self.assertIsNotNone(шаблон, "регулярка разбора ссылки изменилась — обнови тест")
        движок = re.compile(r"^ans_(" + шаблон.group(1) + r")_(\d+)$")
        for код in sorted(_коды_в_кнопках_бота()):
            if код == "gv":
                continue                      # у него свой разбор: хвост не число
            m = движок.match(f"ans_{код}_0")
            self.assertIsNotNone(m, f"ссылка ans_{код}_0 не разбирается вовсе")
            self.assertEqual(m.group(1), код,
                             f"ans_{код}_0 разобралась как «{m.group(1)}»")


if __name__ == "__main__":
    unittest.main()
