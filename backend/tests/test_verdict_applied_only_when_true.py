# -*- coding: utf-8 -*-
"""Отметка «приговор доехал до данных» ставится по ФАКТУ, а не по вере.

Живой дефект 25.08.2026. Первая версия применения ставила отметку сразу после записи —
раз запрос выполнился, значит применено. Проверка базы показала другое: у «Erfolgen»,
«umgeworfen», «verzockt» старое написание осталось в личной карточке, у «Seifenblasen»
и «Verdecken» — в записи пула. Пять слов числились сделанными и больше никогда не были
бы взяты в работу.

Причина: `spread_correction_everywhere` ходит ПО СВЯЗЯМ — карточки берёт условием
`lex_unit_id = <слово>`, записи пула только через найденные карточки. Карточка без
проставленной связи и запись пула, найденная по `word_de`, мимо неё проходят.

Отметка на веру не отличается от отсутствия отметки: она лишь прячет незакрытую правку.
"""
from __future__ import annotations

import backend.word_gate_apply as A


class _Курсор:
    """Подставная база: помнит, что в ней «лежит», и отвечает на счётные запросы."""

    def __init__(self, осталось_мест: int):
        self.осталось = осталось_мест
        self.отмечено: list[str] = []

    def execute(self, sql: str, params=()):
        self._последний = (sql, params)
        if "UPDATE bt_3_word_check SET applied_at" in sql:
            self.отмечено.append(params[0])

    def fetchone(self):
        sql = self._последний[0]
        if "SELECT id FROM bt_3_lex_units" in sql:
            return (1,) if self.осталось else None
        return (self.осталось,)


def test_отметка_не_ставится_пока_старый_текст_лежит_в_базе():
    cur = _Курсор(осталось_мест=1)
    A._отметить(cur, "Erfolgen", "Erfolg")
    assert cur.отмечено == [], (
        "приговор отмечен применённым, хотя старое написание осталось — "
        "слово больше никогда не будет взято в работу")


def test_отметка_ставится_когда_старого_текста_больше_нет():
    cur = _Курсор(осталось_мест=0)
    A._отметить(cur, "Erfolgen", "Erfolg")
    assert cur.отмечено == ["Erfolgen"]


def test_когда_текст_не_менялся_отметка_ставится_без_проверки():
    """«Подтверждено» и «нигде нет» менять ничего не должны — проверять нечего."""
    cur = _Курсор(осталось_мест=5)
    A._отметить(cur, "gehen")
    assert cur.отмечено == ["gehen"]


def test_дочистка_меняет_поле_только_при_полном_совпадении():
    """Замена по ВХОЖДЕНИЮ переписала бы слово внутри чужой фразы — это развоз порчи."""
    import inspect
    исходник = inspect.getsource(A._добить_остатки)
    assert "lower(%s)" in исходник and "LIKE" not in исходник.upper(), \
        "дочистка ищет по вхождению — так она испортит примеры и фразы"
