"""Ночное переименование обязано доехать до ВСЕХ хранилищ, а не до строки словаря.

Живой дефект 25.08.2026. `warm_word_gate` чинил заголовок через `retitle_unit` — и на
этом останавливался. Но экран разбора читает не строку словаря, а личную карточку
человека и общий пул, где лежит КОПИЯ того же текста. Слово объявлялось исправленным,
человек открывал карточку и видел прежнее написание. Ровно это уже было замерено
16.08.2026 («klarzukommen»: word_de починено, translation_de и пул — нет) и описано в
scripts/dict_fix_headwords_everywhere.py, но ночной проход о том выводе не знал.

Тест читает ИСХОДНИК, а не гоняет функцию: поднимать боевую базу ради одного вызова
дороже и хрупче, а проверить надо ровно одно — что эти два вызова ходят парой.
"""
from __future__ import annotations

import ast
import pathlib


def _функция(имя_файла: str, имя_функции: str) -> ast.FunctionDef:
    корень = pathlib.Path(__file__).resolve().parents[1]
    дерево = ast.parse((корень / имя_файла).read_text(encoding="utf-8"))
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.FunctionDef) and узел.name == имя_функции:
            return узел
    raise AssertionError(f"{имя_функции} не найдена в {имя_файла}")


def _зовёт(узел: ast.AST) -> set[str]:
    имена = set()
    for внутри in ast.walk(узел):
        if isinstance(внутри, ast.Call):
            цель = внутри.func
            if isinstance(цель, ast.Name):
                имена.add(цель.id)
            elif isinstance(цель, ast.Attribute):
                имена.add(цель.attr)
    return имена


def test_переименование_ночью_развозится_по_пулу_и_карточкам():
    зовёт = _зовёт(_функция("german_word_gate.py", "warm_word_gate"))
    assert "retitle_unit" in зовёт, "тест устарел: переименование делает уже не эта функция"
    assert "spread_correction_everywhere" in зовёт, (
        "заголовок починен только в строке словаря — человек увидит старое написание "
        "в своей карточке и в общем пуле")


def test_приговор_отмечается_применённым_в_той_же_функции():
    """Иначе вынесенный приговор неотличим от доехавшего до данных.

    25.08.2026 так молча зависли 47 приговоров: ночной проход берёт слово только пока
    его нет в bt_3_word_check, а приговор ложится туда ДО применения.
    """
    исходник = ast.dump(_функция("german_word_gate.py", "warm_word_gate"))
    assert "applied_at" in исходник, "нет отметки о применении — приговор снова потеряется"
