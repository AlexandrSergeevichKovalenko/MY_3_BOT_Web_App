# -*- coding: utf-8 -*-
"""«Работа над ошибками» обязана уметь всё, что умеет её тренажёр.

Повод (10.09.2026, владелец, экран «🔁 Работа над ошибками · der Auspuff»): «А где
пропала иконка сохранения тут в интерактиве с Артиклями?!»

Она не пропадала — её там не было НИКОГДА. Экраны повторов собрали по шаблону
тренажёров (891ed4cf, 05.08.2026), а дискетка появилась в тренажёрах позже
(de3ac55c). Шаблон скопировали один раз, и с тех пор он не догонял оригинал.

Это класс, а не случай: любой будущий экран повторов, собранный «по шаблону
тренажёра», унаследует его на день рождения и потеряет всё, что тренажёр получил
после. Тест держит ровно эту связь: умеет тренажёр забирать слово в словарь —
обязан уметь и его повтор.
"""
import pathlib
import re
import unittest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИГРЫ = КОРЕНЬ / "frontend/src/answer"

# Сохранение слова на экране: общая дискетка либо собственная кнопка сохранения.
УМЕЕТ_СОХРАНЯТЬ = re.compile(r"SaveWordChip|saveWord\s*[=(]")


class ПовторНеБеднееТренажёра(unittest.TestCase):

    def _пары(self):
        пары = []
        for повтор in sorted(ИГРЫ.glob("*ReviewGame.jsx")):
            тренажёр = ИГРЫ / повтор.name.replace("ReviewGame.jsx", "LearnGame.jsx")
            if тренажёр.exists():
                пары.append((тренажёр, повтор))
        return пары

    def test_пары_тренажёр_повтор_вообще_нашлись(self):
        """Если файлы переименуют, тест обязан упасть здесь, а не тихо пройти на пустом
        списке — молчащая проверка неотличима от сломанной."""
        self.assertTrue(self._пары(), "не нашлось ни одной пары *LearnGame/*ReviewGame")

    def test_умеет_тренажёр_забрать_слово_умеет_и_повтор(self):
        бедные = []
        for тренажёр, повтор in self._пары():
            учит = УМЕЕТ_СОХРАНЯТЬ.search(тренажёр.read_text(encoding="utf-8"))
            повторяет = УМЕЕТ_СОХРАНЯТЬ.search(повтор.read_text(encoding="utf-8"))
            if учит and not повторяет:
                бедные.append(повтор.name)
        self.assertEqual(
            бедные, [],
            "экран повторов потерял сохранение слова, которое есть в его тренажёре: "
            "человек видит слово, на котором ошибся, и забрать его некуда",
        )


if __name__ == "__main__":
    unittest.main()
