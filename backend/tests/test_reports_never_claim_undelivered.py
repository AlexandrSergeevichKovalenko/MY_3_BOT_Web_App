# -*- coding: utf-8 -*-
"""Ни один отчёт админам не имеет права сказать «отправлено», не доставив никому.

Поймано живьём 02.09.2026. Отправлял владельцу недельный отчёт: токен оказался не
боевым, Telegram ответил 401 Unauthorized, письмо не ушло НИКОМУ — а функция вернула
{"ok": True, "sent": 0} и пометила прогон «выполнено». То есть письмо могло бы не
приходить неделями, а в журнале планировщика стояло бы «всё хорошо».

Владелец 19.08.2026: «молчащий механизм неотличим от сломанного».

Проверка 02.09.2026 показала, что дыра была во ВСЕХ десяти отчётах — экономика, разбор
артиклей, отсев артиклей, пул словаря, потолки, расходы провайдеров, прогрев Wiktionary
и словоформы. Поэтому тест сторожит не одно место, а КЛАСС: он читает исходники и
требует, чтобы у каждой такой отправки был вердикт по факту доставки.

Тест намеренно читает ТЕКСТ файлов, а не вызывает функции: поднять десять отчётов с их
базами и сетью в тесте нельзя, а вот доказать, что правило стоит в каждом, — можно.
"""
import io
import os
import re

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Файл → сколько в нём отправок отчёта админам (замер 02.09.2026).
ОТЧЁТЫ = {
    "admin_economics.py": 4,
    "article_review.py": 1,
    "article_retire_review.py": 1,
    "dictionary_pool_report.py": 1,
    "cap_health_report.py": 1,
    "provider_cost_truth.py": 1,
    "wiktionary_warm.py": 1,
    "lex_form_index_sweep.py": 1,
}

_УСПЕХ = re.compile(r'return \{"ok": True, "sent": sent')


def _исходник(имя: str) -> str:
    return io.open(os.path.join(BACKEND, имя), encoding="utf-8").read()


def test_все_отчёты_на_месте():
    """Если отчёт переименовали или удалили — тест обязан это заметить, а не молчать."""
    for имя, сколько in ОТЧЁТЫ.items():
        src = _исходник(имя)
        assert len(_УСПЕХ.findall(src)) == сколько, (
            f"{имя}: число отправок отчёта изменилось — проверь, что правило "
            f"«ноль доставленных = провал» стоит и в новом месте"
        )


def test_у_каждой_отправки_есть_вердикт_по_факту_доставки():
    """Перед каждым «ok: True» обязан стоять отказ при нуле доставленных."""
    for имя in ОТЧЁТЫ:
        src = _исходник(имя)
        for m in _УСПЕХ.finditer(src):
            окно = src[max(0, m.start() - 900):m.start()]
            assert "if not sent:" in окно, (
                f"{имя}, строка {src[:m.start()].count(chr(10)) + 1}: отчёт вернёт "
                f"«отправлено», даже если не дошёл никому"
            )
            assert '"ok": False' in окно, (
                f"{имя}: при нуле доставленных наружу обязан уходить ok=False"
            )


def test_статус_прогона_зависит_от_доставки_а_не_от_факта_запуска():
    """Планировщик не должен записывать «выполнено», когда письмо не дошло.

    Способов сделать это честно ДВА, и оба годятся:
      • статус считается по факту — status="completed" if sent else "failed";
      • либо при нуле доставленных функция выходит РАНЬШЕ, сама пометив прогон
        неудачным (так сделано в lex_form_index_sweep — там ещё и «partial»,
        когда дошло не всем).
    Тест требует любой из двух, а не конкретную букву: иначе он запрещал бы делать
    лучше, чем написано в нём самом.
    """
    for имя in ОТЧЁТЫ:
        src = _исходник(имя)
        for m in _УСПЕХ.finditer(src):
            окно = src[max(0, m.start() - 1400):m.start()]
            if "finish_scheduler_run_guard" not in окно:
                continue  # у этой отправки сторожа прогона нет — нечего проверять
            по_факту = 'status="completed" if sent else "failed"' in окно
            блок = окно[окно.rindex("if not sent:"):] if "if not sent:" in окно else ""
            вышли_раньше = "return" in блок and 'status="failed"' in блок
            assert по_факту or вышли_раньше, (
                f"{имя}: сторож прогона помечает «выполнено» независимо от доставки"
            )
