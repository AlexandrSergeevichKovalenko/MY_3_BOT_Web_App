# -*- coding: utf-8 -*-
"""Русский перевод как ВТОРОЙ ГОЛОС о части речи немецкого слова.

Откуда взялось (владелец, 24–25.08.2026)
────────────────────────────────────────
Карточка «die Mies» — «Паршивый» — с выдуманными значениями про неудачников. Корень:
человек ищет слово, и с клавиатуры оно приходит с ЗАГЛАВНОЙ буквы — это первое и
единственное слово запроса. В немецком заглавная означает существительное, поэтому
«reif» («зрелый») уезжало в базу как «Reif», справочник честно отвечал про существительное
«der Reif» (иней), а модель сочиняла под него смыслы.

Русский перевод писал человек, и он не врёт: «Зрелый» — прилагательное. Он и есть
второй голос.

ЧТО ЭТОТ ТЕСТ СТОРОЖИТ
1. Определитель отличает существительное от прилагательного и глагола.
2. Он НЕ пользуется окончанием слова. Предыдущая попытка — регулярка по окончанию —
   развалилась на живых данных: «Последовательность» и «Ясность» кончаются на «ть» и
   объявлялись глаголами, «печь» на «чь» — тоже. Эти четыре случая здесь закреплены,
   чтобы регулярка не вернулась.
3. Спорное остаётся спорным. «Простой» — и прилагательное, и существительное; «Правда» —
   и существительное, и частица. По ним решения не принимается.
4. Оборот из нескольких слов — не слово: «не знаем», а не догадка.
5. Отсутствие библиотеки НЕ роняет продукт и НЕ включает угадывание.
"""
from __future__ import annotations

import pytest

from backend import russian_part_of_speech as ru
from backend.russian_part_of_speech import (
    ADJECTIVE, AMBIGUOUS, NOUN, UNKNOWN, VERB,
    part_of_speech, proves_a_noun, proves_not_a_noun,
)


class TestОтличаетЧастиРечи:
    @pytest.mark.parametrize("слово", ["Нос", "Черепаха", "Кислород", "Затылок", "Изгнанник"])
    def test_существительное(self, слово):
        assert part_of_speech(слово) == NOUN
        assert proves_a_noun(слово)
        assert not proves_not_a_noun(слово)

    @pytest.mark.parametrize("слово", ["Зрелый", "Чистый", "Паршивый", "Тупой", "Ничейный"])
    def test_прилагательное(self, слово):
        assert part_of_speech(слово) == ADJECTIVE
        assert proves_not_a_noun(слово)
        assert not proves_a_noun(слово)

    @pytest.mark.parametrize("слово", ["Грести", "Завтракать", "Заниматься"])
    def test_глагол(self, слово):
        assert part_of_speech(слово) == VERB
        assert proves_not_a_noun(слово)


class TestОкончаниеНеЯвляетсяЧастьюРечи:
    """Четыре случая, на которых развалилась регулярка 24.08.2026. Не убирать."""

    @pytest.mark.parametrize("слово", [
        "Последовательность",   # кончается на «ть» — регулярка звала глаголом
        "Ясность",              # то же
        "Печь",                 # кончается на «чь» — то же
        "Принадлежность",       # то же
    ])
    def test_существительное_с_глагольным_хвостом(self, слово):
        assert part_of_speech(слово) == NOUN, "окончание — не часть речи"
        assert proves_a_noun(слово)


class TestСпорноеОстаётсяСпорным:
    @pytest.mark.parametrize("слово", ["Простой", "Правда"])
    def test_два_верных_разбора_дают_спорно(self, слово):
        assert part_of_speech(слово) == AMBIGUOUS
        # Ни одно из двух утверждений не делается: выбирать за человека нельзя.
        assert not proves_a_noun(слово)
        assert not proves_not_a_noun(слово)


class TestНеСловоНеРазбирается:
    @pytest.mark.parametrize("текст", [
        "держать пари", "ездить верхом", "в стороне, вдали",
        "", "   ", "Reif", "die Nase", "123",
    ])
    def test_оборот_и_нерусское_дают_не_знаем(self, текст):
        assert part_of_speech(текст) == UNKNOWN
        assert not proves_a_noun(текст)
        assert not proves_not_a_noun(текст)


class TestБезБиблиотекиНеУгадываем:
    def test_отсутствие_pymorphy3_даёт_не_знаем(self, monkeypatch):
        monkeypatch.setattr(ru, "_get_analyzer", lambda: None)
        assert part_of_speech("Зрелый") == UNKNOWN
        assert not proves_a_noun("Нос")
        assert not proves_not_a_noun("Зрелый")
