def test_экран_зовёт_к_кнопке_которая_на_нём_есть():
    """⛔ ИМЕННО ЭТО И БЫЛО СЛОМАНО: надпись звала «спроси заново», а кнопку прятал
    `isCard` — то есть у вопросов о переводе её не было вовсе."""
    jsx = open(os.path.join(BASE, "frontend/src/answer/PhraseReviewScreen.jsx"),
               encoding="utf-8").read()

    блок = jsx[jsx.index("onClick={rejudge}") - 400: jsx.index("onClick={rejudge}") + 200]
    assert "{!isPanel ?" in блок, (
        "кнопка доспроса обязана быть у вопросов о переводе, а не только у грамматики")
    assert "Спросить заново" in блок

    # Старая надпись «Впиши свой или спроси заново» осталась только там, где кнопка
    # действительно есть и зовётся «Пересудить», — у грамматики.
    for текст in ("Спросили заново", "Нажми «Спросить заново» внизу"):
        assert текст in jsx, f"нет честной надписи: {текст}"


