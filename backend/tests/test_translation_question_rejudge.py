# -*- coding: utf-8 -*-
"""ВОПРОС О ПЕРЕВОДЕ ОБЯЗАН ПОЛУЧИТЬ ОТВЕТ «КАК ПРАВИЛЬНО» — или метку, что спросили.

Владелец 16.09.2026 открыл экран спорных фраз и увидел на «Ich kündige die Stelle»
диагноз без единого варианта: «Готового варианта голос не назвал». Модель за эту фразу
была оплачена ещё 27.08.2026 — но тогда её не просили назвать перевод, ключ `fix`
появился только 31.08.2026. Получить вариант такая запись не могла НИЧЕМ: пересуд на
экране был скрыт, ночь не берёт единицу с открытым вопросом, вставка идёт
`ON CONFLICT DO NOTHING`, слепой массовый пересуд этот вид отфильтровывает.

Замер на живой базе 16.09.2026: 68 вопросов в очереди, 15 из них в этом состоянии.

Тесты держат три вещи, которые нельзя потерять:
  1. доспрос кладёт готовый вариант туда, откуда его читает экран;
  2. доспрос ставит метку — второй раз за ту же запись мы не платим;
  3. отбор на доспрос эту метку уважает, а экран зовёт к кнопке, которая есть.
"""
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def test_вариант_модели_едет_в_поле_которое_читает_экран():
    """`better` от судьи обязан лечь в `fix`: экран рисует кнопку именно по нему."""
    from backend.translation_links import голос_после_доспроса

    голос = голос_после_доспроса(
        [{"verdict": "doubt", "why": "старая претензия"}],
        {"checked": True, "ok": False, "why": "русское не про то",
         "better": "Я увольняюсь с этой должности."})

    assert голос["fix"] == "Я увольняюсь с этой должности."
    assert голос["field"] == "translation", "без имени поля экран не знает, о чём спор"
    assert голос["why"] == "русское не про то", "претензия свежая, от того же доспроса"
    assert голос["why_before"] == "старая претензия", "прежнюю формулировку не теряем"


def test_доспрос_всегда_оставляет_метку():
    """Метка — это то, что не даёт спрашивать одну запись каждую ночь заново."""
    from backend.translation_links import голос_после_доспроса

    for verdict in ({"checked": True, "ok": False, "why": "не то", "better": "верный"},
                    {"checked": True, "ok": False, "why": "фразы такой нет", "better": ""},
                    {"checked": True, "ok": True, "why": "", "better": ""}):
        голос = голос_после_доспроса([{"why": "было"}], verdict)
        assert isinstance(голос.get("rejudge"), dict), verdict
        assert голос["rejudge"]["at"], "без даты метка не доказывает, что спрашивали"
        assert голос["rejudge"]["ok"] is bool(verdict["ok"])


def test_согласие_судьи_не_закрывает_вопрос_само():
    """Доспрос снял претензию — решение всё равно за владельцем.

    Владелец 25.08.2026: молчание не согласие. Здесь то же самое с другой стороны —
    передумавшая модель не имеет права распорядиться его словарём вместо него."""
    from backend.translation_links import голос_после_доспроса

    голос = голос_после_доспроса(
        [{"verdict": "doubt", "why": "русское про другое"}],
        {"checked": True, "ok": True, "why": "перевод верен", "better": "что угодно"})

    assert голос["verdict"] == "ok"
    assert голос["fix"] == "", "при согласии заменять нечего — кнопки быть не должно"
    assert голос["why"] == "русское про другое", "владелец видел эту претензию, не подменяем"
    assert голос["rejudge"]["ok"] is True, "экран скажет, что голос передумал"


def test_отбор_на_доспрос_уважает_метку_и_пустой_fix():
    """Условие отбора — одно на всех: и на работу, и на счётчик, и на обещание."""
    from backend.translation_links import _ВОПРОС_БЕЗ_ВАРИАНТА

    условие = " ".join(_ВОПРОС_БЕЗ_ВАРИАНТА.split())
    assert "j->'rejudge' IS NOT NULL" in условие, (
        "без этого ночь будет платить за одну и ту же запись каждые сутки")
    assert "j->>'fix'" in условие, "вопрос с готовым вариантом доспрашивать незачем"
    assert "'translation'" in условие, "чужие виды вопросов этот судья не разбирает"


def test_счётчик_и_обещание_считают_одним_правилом():
    """Обещание меряет ровно то, что чинит ночь, — иначе они разъедутся молча."""
