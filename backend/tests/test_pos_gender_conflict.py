"""Часть речи спорит с родом: решает словарь, а не наша догадка.

Замер 13.09.2026 на живой базе: 21 статья вида «прилагательное с родом der». Род в
немецком бывает только у существительного, поэтому одно из двух полей неверно. На
экране это видно: формула показа верит пометке «прилагательное» и не поднимает
заглавную — человек читает «ruhestände», «schiffwrack», «zEITSCHRIFT» (36 карточек).

Почему нельзя «есть род — значит существительное»: справочник склонений отвечает
«der» на «hart» (это про фамилию Hart, а у нас прилагательное «твёрдый») и «die» на
«Läster» (а у нас «клеветник», то есть der Lästerer). Обе правки испортили бы слово.
"""
import unittest

from backend.pos_gender_conflict import (
    ВЛАДЕЛЬЦУ, НЕ_СПРОСИЛИ, РЕШЕНО_НЕ_СУЩЕСТВИТЕЛЬНОЕ, РЕШЕНО_СУЩЕСТВИТЕЛЬНОЕ,
    варианты_написания, разобрать,
)


def словарь(ответы: dict):
    """DWDS-заглушка: {написание: часть речи | '' | None}. Чего нет в словаре — ''."""
    return lambda слово: ответы.get(слово, "")


class СпрашиваемПравильныеНаписания(unittest.TestCase):
    def test_строчное_и_заглавное(self):
        self.assertEqual(варианты_написания("ruhestände"), ["ruhestände", "Ruhestände"])

    def test_капс_приводится_к_словарному_виду(self):
        """«zEITSCHRIFT» — выделенное в тексте слово, а не немецкое написание."""
        self.assertIn("Zeitschrift", варианты_написания("zEITSCHRIFT"))


class РешениеБерётсяИзСловаря(unittest.TestCase):
    def test_существительное_опознаётся_по_заглавной_форме(self):
        решение, написание, ответ = разобрать(
            "zEITSCHRIFT", словарь({"Zeitschrift": "Substantiv"}))
        self.assertEqual(решение, РЕШЕНО_СУЩЕСТВИТЕЛЬНОЕ)
        self.assertEqual(написание, "Zeitschrift")
        self.assertEqual(ответ, "Substantiv")

    def test_прилагательное_остаётся_прилагательным(self):
        """`hart` — ловушка справочника склонений: он отвечает «der» про фамилию."""
        решение, написание, _ = разобрать("hart", словарь({"hart": "Adjektiv"}))
        self.assertEqual(решение, РЕШЕНО_НЕ_СУЩЕСТВИТЕЛЬНОЕ)
        self.assertEqual(написание, "hart")

    def test_глагол_тоже(self):
        решение, _, _ = разобрать("übersteigen", словарь({"übersteigen": "Verb"}))
        self.assertEqual(решение, РЕШЕНО_НЕ_СУЩЕСТВИТЕЛЬНОЕ)

    def test_обрубок_уходит_владельцу(self):
        """`Läster` — обрубок от «der Lästerer». Словарь его не знает, и это сигнал."""
        решение, написание, _ = разобрать("Läster", словарь({}))
        self.assertEqual(решение, ВЛАДЕЛЬЦУ)
        self.assertEqual(написание, "")

    def test_молчание_сети_это_не_приговор(self):
        """DWDS не ответил — ничего не решаем и ждём следующей ночи. Путать «не знаю»
        с «нет такого слова» здесь нельзя: от этого зависит, испортим ли мы слово."""
        решение, _, _ = разобрать("ruhestände", lambda _слово: None)
        self.assertEqual(решение, НЕ_СПРОСИЛИ)

    def test_молчание_на_одном_написании_не_мешает_ответу_на_другом(self):
        ответы = {"festschreibung": None, "Festschreibung": "Substantiv"}
        решение, написание, _ = разобрать("festschreibung",
                                          lambda с: ответы.get(с, ""))
        self.assertEqual(решение, РЕШЕНО_СУЩЕСТВИТЕЛЬНОЕ)
        self.assertEqual(написание, "Festschreibung")


if __name__ == "__main__":
    unittest.main()
