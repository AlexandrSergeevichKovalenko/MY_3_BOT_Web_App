"""Сторож: ночная переписка заголовков трогает ТОЛЬКО немецкие слова.

Эта ночная работа (03:50) переписывает заголовок личной карточки по немецкому
справочнику форм — word_de, word_ru, translation_ru и весь разбор. До 16.09.2026 она
брала всё подряд, язык карточки не спрашивался. Пока база одноязычная, это незаметно;
в день, когда рядом ляжет английское слово, «Gift» (подарок) станет «das Gift» (яд)
молча, ночью, без следа на экране. Испорченную запись не вернуть.
"""
import inspect
import os

os.environ.setdefault("SKIP_STARTUP_SCHEMA_BOOTSTRAP", "1")


def test_отбор_кандидатов_спрашивает_язык():
    from backend import form_headword_sweep
    исходник = inspect.getsource(form_headword_sweep._candidates)
    assert "это_немецкое" in исходник, "ночная переписка снова берёт слова без разбора языка"
    assert "native_language" in исходник, "родной язык человека не запрашивается"


def test_правка_карточек_спрашивает_язык():
    """Одно написание лежит у разных людей в разных парах. Отбор кандидатов решает,
    БРАТЬ ли написание, а этот — ЧЬЮ карточку трогать. Нужны оба."""
    from backend import form_headword_sweep
    исходник = inspect.getsource(form_headword_sweep._fix_surface)
    assert "это_немецкое" in исходник, "правка карточек снова идёт без разбора языка"


def test_язык_берётся_из_общего_ответчика_а_не_своим_условием():
    """⚠ Условие «есть ли de в паре» НЕВЕРНО: у пары en→de немецкий — родной язык
    человека, а слово английское. Такую копию правила писать запрещено — ответчик один
    на всё приложение."""
    from backend import form_headword_sweep
    исходник = inspect.getsource(form_headword_sweep)
    assert "from backend.lang_of_word import это_немецкое" in исходник
    assert "target_lang = 'de'" not in исходник, "своё условие про немецкий — так нельзя"
    assert "target_lang='de'" not in исходник, "своё условие про немецкий — так нельзя"
