# -*- coding: utf-8 -*-
"""«Нужен ты» пишется только там, где владельцу есть куда нажать.

ПОВОД, 29.08.2026. Владелец получил строку «📖 Словарь: 1 записей машина закрыть не
может — нужен ты», открыл разбор и увидел под заголовком «Нужен человек» ровно одну
строку: «немецкий текст пишется мимо двери — новый путь записи — нужен я, а не
владелец». То есть его позвали на МОЮ задачу, кнопки под которой нет и быть не может.

Дословно: «здесь ни одной кнопки нету, здесь нужна какая-то моя активность или нет?
если нет — зачем это мне нужно?»

Причина: куч было ДВЕ — «чинится само» и «нужен человек». Всё, что не чинится само,
падало владельцу, включая правки в коде. Теперь куч три, и эта проверка стережёт
границу: работа разработчика владельца не зовёт.
"""
import unittest
from unittest import mock

from backend import dictionary_integrity as целостность


def _прогон(broken: dict, failed: dict | None = None):
    return {"broken": broken, "failed": failed or {},
            "total": sum(broken.values()), "samples": {}}


class МояРаботаНеЗовётВладельца(unittest.TestCase):
    ЧИНЮ_Я = "немецкий текст пишется мимо двери"

    def test_the_rule_is_filed_as_my_work(self):
        кто, _ = целостность.CLOSED_BY[self.ЧИНЮ_Я]
        self.assertEqual(целостность.NEEDS_ME, кто,
                         "правка в коде снова числится задачей владельца")

    def test_owner_line_does_not_summon_him_for_my_work(self):
        with mock.patch.object(целостность, "run", return_value=_прогон({self.ЧИНЮ_Я: 1})):
            строка = целостность.owner_line()
        self.assertNotIn("нужен ты", строка.lower(),
                         "владельца зовут на задачу, под которой нет кнопки")
        self.assertIn("не твоя", строка.lower())

    def test_owner_line_still_summons_him_when_there_is_a_button(self):
        """Обратная сторона: там, где кнопка ЕСТЬ, звать обязаны — иначе правка
        29.08.2026 превратит отчёт в вечное «всё хорошо».

        ┌─ ПРОВЕРЕНО 29.08.2026. НЕ ПОДНИМАТЬ КАК НАХОДКУ. ────────────────────────┐
        │ Сегодня в CLOSED_BY НЕТ НИ ОДНОГО правила с NEEDS_OWNER: единственное,   │
        │ что там лежало, оказалось моей задачей и переехало в NEEDS_ME. Значит     │
        │ отчёт о целостности сейчас не может позвать владельца, и это НОРМА, а не  │
        │ дефект: звать его пока не по чему. Поэтому правило с кнопкой здесь        │
        │ подставляется искусственно — тест стережёт саму ВЕТКУ, чтобы она не       │
        │ отмерла к моменту, когда правило с кнопкой появится.                      │
        └──────────────────────────────────────────────────────────────────────────┘
        """
        свои = dict(целостность.CLOSED_BY)
        свои["правило с кнопкой"] = (целостность.NEEDS_OWNER, "разбор в мини-аппе")
        with mock.patch.object(целостность, "CLOSED_BY", свои):
            with mock.patch.object(целостность, "run",
                                   return_value=_прогон({"правило с кнопкой": 3})):
                строка = целостность.owner_line()
                текст = "\n".join(целостность.report_lines())
        self.assertIn("нужен ты", строка.lower())
        self.assertIn("НУЖЕН ТЫ", текст)
        self.assertNotIn("От тебя сейчас ничего не нужно", текст)

    def test_unknown_rule_is_mine_not_his(self):
        with mock.patch.object(целостность, "run",
                               return_value=_прогон({"правило без хозяина": 2})):
            строка = целостность.owner_line()
        self.assertNotIn("нужен ты", строка.lower(),
                         "правило, которому я забыл назначить хозяина, зовёт владельца")

    def test_report_says_plainly_when_nothing_is_needed_from_him(self):
        with mock.patch.object(целостность, "run", return_value=_прогон({self.ЧИНЮ_Я: 1})):
            текст = "\n".join(целостность.report_lines())
        self.assertIn("От тебя сейчас ничего не нужно", текст)
        self.assertIn("Моя работа, не твоя", текст)
        self.assertNotIn("Нужен человек", текст)


if __name__ == "__main__":
    unittest.main()
