"""Сторож общей дорожки предложений: чужой язык туда не попадёт.

Дорожка ОДНА НА ВСЕХ. Чужой язык здесь уедет не к одному человеку, а ко всем сразу —
это единственное место такого рода во всей переписи 15.09.2026.

До 17.09.2026 язык не проверялся вовсе, и ноль английских записей проходил отбор по
двум СЛУЧАЙНОСТЯМ, а не по правилу: у английских строк пуста колонка word_de, а
«целевая сторона» у пары en→ru русская, то есть с кириллицей. Обе случайности
исчезают в тот день, когда английский начнёт заполнять эти колонки.
"""
import inspect
import os

import pytest

os.environ.setdefault("SKIP_STARTUP_SCHEMA_BOOTSTRAP", "1")


def test_отбор_дорожки_спрашивает_язык():
    from backend import database
    src = inspect.getsource(database.pick_words_for_sentence_track)
    assert "sql_немецкое_наверняка" in src, "дорожка снова берёт материал без разбора языка"
    assert "НЕМЕЦКАЯ_ПАРА" in src


def test_два_вида_правила_согласны_между_собой():
    """Правило про язык живёт в одном месте, но у него две формы: питоновская и кусок
    SQL. Разъедутся — и дорожка начнёт брать не то, а поймать это будет нечем."""
    from backend.lang_of_word import немецкое_наверняка, sql_немецкое_наверняка
    кусок = sql_немецкое_наверняка("e")
    пары = [("ru", "de", True), ("de", "ru", True), ("en", "ru", False),
            ("ru", "en", False), ("en", "de", False), ("ru", "it", False)]
    for s, t, ожидание in пары:
        # питоновская форма
        assert немецкое_наверняка(source_lang=s, target_lang=t) is ожидание
        # форма SQL — вычисляем её смысл теми же сравнениями, что стоят в тексте
        sql_ответ = ((s == "ru" and t == "de") or (s == "de" and t == "ru"))
        assert sql_ответ is ожидание, f"кусок SQL разошёлся с питоном на паре {s}→{t}"
    assert "source_lang" in кусок and "target_lang" in кусок


def test_алиас_таблицы_проверяется():
    """«Не склеивать SQL из непроверенного» не имеет исключений «для своих»."""
    from backend.lang_of_word import sql_немецкое_наверняка
    assert sql_немецкое_наверняка("e").startswith("((lower(e.")
    for плохой in ("e; DROP TABLE", "e.x", "", None, "1e"):
        with pytest.raises(ValueError):
            sql_немецкое_наверняка(плохой)
