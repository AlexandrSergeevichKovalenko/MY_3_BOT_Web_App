from __future__ import annotations

import json
import re

# ── ПРАВИЛО. Три вида хвоста, повторённого 4 и более раз подряд В КОНЦЕ текста. ──
# Питоновские версии — для уборки и тестов.
MANGLED_PUNCT = re.compile(r"([.?!])\1{3,}\s*$")
MANGLED_WORD = re.compile(r"(?:^|\s)(\S+)(?:\s+\1){3,}\s*$")
MANGLED_LETTER = re.compile(r"(\w)\1{3,}\s*$")

# ЧЕТВЁРТОЕ ПРАВИЛО — порча НЕ в конце строки (добавлено 21.08.2026).
#
# Три правила выше привязаны к концу текста, и это верно для колонок: там лежит один
# заголовок. Но внутри разбора порча попадает в СЕРЕДИНУ предложения, и тогда конец
# строки чистый. Живой случай, который три правила пропускали:
#
#     "sterile Gazennnnn wird oft in der Wundversorgung benutzt."
#      ^^^^^^^^^^^^^^^^^ порча здесь, а строка кончается точкой
#
# Почему требуется ОСНОВА в три буквы. Замер 21.08.2026 по всем 10454 разборам живой
# базы: правило «буква повторена 4+ раз» без основы даёт 6 попаданий, и пять из них —
# законный текст, наши же мнемоники:
#
#     «представьте звук „пииии“, чтобы легче запомнить»    ← законно, основа «п»
#     «Звук „рррр“ передаёт движение по кругу»              ← законно, основы нет
#     «sterile Gazennnnnn»                                  ← порча, основа «Gaze»
#
# У порчи хвост прилеплен к целому слову, у мнемоники повтор и есть всё слово.
# С основой правило даёт ровно 1 попадание из 10454 — настоящую порчу и ничего больше.
#
# Это правило ПИТОНОВСКОЕ и в SQL_MANGLED не идёт: там оно и не нужно (в колонке лежит
# заголовок, а не предложение), а цена ошибки выше — CHECK роняет запись целиком.
MANGLED_LETTER_INSIDE = re.compile(r"\b(\w{3,}?)(\w)\2{3,}\b", re.UNICODE)

# ПЯТОЕ ПРАВИЛО — повтор СЛОВА не в конце строки (добавлено 21.08.2026).
#
# То же слепое пятно, что и у четвёртого, только шаг крупнее. `MANGLED_WORD` привязано
# к концу текста, а в разборе порча садится в начало или в середину предложения:
#
#     "POV: POV: POV: POV: POV: POV: Er will ins Freibad gehen!"
#      ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^ порча здесь, а строка кончается восклицанием
#
# Порог тот же — ЧЕТЫРЕ повтора и больше. Три оставлены живому языку: «ganz, ganz, ganz
# vorsichtig» и «nein nein nein» встречаются в цитатах и в наших же мнемониках, и ронять
# их нельзя. Замер 21.08.2026 по 3000 разборам живой базы: правило даёт 0 попаданий на
# законном тексте.
#
# Как и четвёртое, это правило ПИТОНОВСКОЕ и в SQL_MANGLED не идёт: в колонке лежит
# заголовок, а не предложение, а цена ошибки там выше — CHECK роняет запись целиком.
MANGLED_WORD_INSIDE = re.compile(r"(?:^|\s)(\S+)(?:\s+\1){3,}(?:\s|$)")

# ШЕСТОЕ ПРАВИЛО — повтор буквы В НАЧАЛЕ слова (добавлено 21.08.2026).
#
# Механизм порчи один, но хвост прилипает с ТОЙ стороны, с какой «новое» отличается от
# «старого». Все пять правил выше ловят прилипание справа, потому что именно так легли
# 16 записей 16.08. А `dict_split_multi_phrase_cards.py` держал пару правок, где новое
# отличается СЛЕВА: «as schlägst du vor?» → «Was schlägst du vor?». Повторный прогон дал
# бы «WWas», третий «WWWas» — и этого не ловило ни одно правило.
#
# Саму дыру закрыли (скрипт стал безобидным при повторе), но правило дописано, чтобы
# набор был ПОЛНЫМ по доказанному механизму: слева и справа, буквой, словом и знаком.
# Неполный набор — это и есть приглашение к шестому заходу по кругу.
#
# ТОЛЬКО БУКВЫ, не цифры. Первая версия правила стояла на `\w`, а он включает цифры — и
# правило поймало «11118» и метки времени «2026-08-16T01:20:32.777708». Внутри разбора
# лежат и числа, и даты, поэтому класс сужен до букв.
#
# Ложных срабатываний на буквах быть не может: ни в немецком, ни в русском нет слова,
# начинающегося с четырёх одинаковых букв. Проверено на живой базе: 0 попаданий на
# 83 256 заголовках и 4000 разборах.
_БУКВА = r"[^\W\d_]"
MANGLED_LETTER_AHEAD = re.compile(rf"\b({_БУКВА})\1{{3,}}{_БУКВА}", re.UNICODE)

MANGLED_ALL = (MANGLED_PUNCT, MANGLED_WORD, MANGLED_LETTER,
               MANGLED_LETTER_INSIDE, MANGLED_WORD_INSIDE, MANGLED_LETTER_AHEAD)

# POSIX-версии того же правила — для CHECK-ограничений в самой базе.
#
# Правила ОТДЕЛЬНЫЕ, а не склеенные в одно. Склеенное я написал и получил от Postgres
# «invalid backreference number»: в общей регулярке номера скобок сдвигаются, и обратная
# ссылка начинает указывать не туда. Отдельные считают свои скобки сами, и четвёртое
# правило можно добавить, ничего не пересчитывая.
SQL_MANGLED = (
    r"([.?!])\1{3,}[[:space:]]*$",
    r"(^|[[:space:]])([^[:space:]]+)([[:space:]]+\2){3,}[[:space:]]*$",
    r"([[:alnum:]])\1{3,}[[:space:]]*$",
)

# ── ГДЕ ИСКАТЬ. Один список на всё приложение. ──
# (таблица, обычные текстовые колонки, колонки с разбором внутри)
STORAGES = (
    ("bt_3_lex_units", ("display", "lemma"), ("card",)),
    ("bt_3_webapp_dictionary_queries", ("word_de", "translation_de"), ("response_json",)),
    ("bt_3_dictionary_entries",
     ("source_text", "word_de", "translation_de"), ("response_json",)),
)


def is_mangled(text) -> bool:
    """Испорчен ли ЭТОТ текст. Единственное место, где принимается такое решение."""
    value = str(text or "")
    return any(rule.search(value) for rule in MANGLED_ALL)


def mangled_strings_inside(node) -> list[str]:
    """Все испорченные строки внутри разбора — на любой глубине.

    Разбор это дерево из словарей и списков, и порча может лежать не в заголовке, а в
    примере или в форме. Проверка только верхнего уровня — та же половинчатость, из-за
    которой тема открывалась заново.
    """
    found: list[str] = []
    if isinstance(node, str):
        if is_mangled(node):
            found.append(node)
    elif isinstance(node, dict):
        for value in node.values():
            found.extend(mangled_strings_inside(value))
    elif isinstance(node, list):
        for value in node:
            found.extend(mangled_strings_inside(value))
    return found


def undo_candidates(text: str) -> list[str]:
    """Каким текст был ДО размножения — все возможные варианты, от одного повтора.

    Сколько повторов было в исходнике, мы не решаем сами: перечисляем варианты, а
    выбирает из них свидетель — `lemma_key`, которого та транзакция не касалась.
    Догадка вместо совпадения со свидетелем здесь запрещена.
    """
    out: list[str] = []
    match = MANGLED_PUNCT.search(text)
    if match:
        head, mark = text[: match.start()], match.group(1)
        return [head + mark * keep for keep in range(1, len(match.group(0).strip()) + 1)]
    match = MANGLED_LETTER.search(text)
    if match:
        head, letter = text[: match.start()], match.group(1)
        return [head + letter * keep for keep in range(1, len(match.group(0).strip()) + 1)]
    match = MANGLED_WORD.search(text)
    if match:
        chunk = match.group(1)
        head = text[: match.start()].rstrip()
        total = len(re.findall(r"\S+", match.group(0)))
        for keep in range(0, total):
            tail = (" " + " ".join([chunk] * keep)) if keep else ""
            out.append((head + tail).strip())
    return out


def collapse_multiplied(text: str) -> str:
    """Свернуть размноженный хвост до ОДНОГО вхождения — где бы он ни стоял.

    Дополняет `undo_candidates`, а не заменяет её. Разница в том, что там лежит:

        undo_candidates      заголовок — хвост в конце, вариантов несколько,
                             выбирает свидетель (`lemma_key`);
        collapse_multiplied  предложение внутри разбора — хвост в начале или в
                             середине, и вариант ровно один.

    Почему один: механизм порчи доказан — одна и та же замена применена шесть раз к
    накапливающейся строке, значит в исходнике кусок стоял один раз. Это не догадка о
    длине хвоста, а известное свойство поломки.

    Живёт ЗДЕСЬ, рядом с признаком, а не в скрипте уборки: у починки и у поиска должно
    быть одно понятие порчи, иначе они разъедутся — ровно так тема и открывалась заново.
    Результат всё равно принимает тот, кто чинит, — по своему свидетелю.
    """
    def _одно(m: "re.Match") -> str:
        целиком = m.group(0)
        # Разделители по краям возвращаем на место: правило захватывает пробел слева
        # и справа, и без них соседние слова слипаются («POV:Er» вместо «POV: Er»).
        слева = целиком[: m.start(1) - m.start()]
        справа = целиком[-1] if целиком[-1:].isspace() else ""
        return слева + m.group(1) + справа

    value = str(text or "")
    value = MANGLED_WORD_INSIDE.sub(_одно, value)
    value = re.sub(r"([.?!])\1{3,}", lambda m: m.group(1), value)
    return value


def scan_everything(cursor) -> dict:
    """Пройти ВСЕ три хранилища одним правилом. Возвращает найденное, ничего не меняя.

    {"таблица.колонка": [(id, текст), …]} — пусто значит пусто, а не «не смотрели».
    """
    found: dict[str, list] = {}
    for table, plain_columns, json_columns in STORAGES:
        for column in plain_columns:
            where = " OR ".join([f"{column} ~ %s"] * len(SQL_MANGLED))
            cursor.execute(
                f"SELECT id, {column} FROM {table} WHERE {where} ORDER BY id;",
                tuple(SQL_MANGLED),
            )
            rows = cursor.fetchall()
            if rows:
                found[f"{table}.{column}"] = rows
        for column in json_columns:
            # У разбора порча может лежать в любой строке внутри дерева, поэтому текстом
            # только СУЖАЕМ круг, а решение принимаем разбором дерева.
            where = " OR ".join([f"{column}::text ~ %s"] * len(SQL_MANGLED))
            cursor.execute(
                f"SELECT id, {column} FROM {table} WHERE {where} ORDER BY id;",
                tuple(SQL_MANGLED),
            )
            rows = []
            for row_id, payload in cursor.fetchall():
                if isinstance(payload, (str, bytes)):
                    try:
                        payload = json.loads(payload)
                    except Exception:
                        continue
                inside = mangled_strings_inside(payload)
                if inside:
                    rows.append((row_id, inside))
            if rows:
                found[f"{table}.{column}"] = rows
    return found
