# -*- coding: utf-8 -*-
"""Сколько карточек анаграмм добрать этой ночью. Решение владельца 13.09.2026.

Повод
─────
Ночной добор считал банк ЦЕЛИКОМ: «есть 12 неснятых карточек — работы нет». Замер
13.09.2026: в банке 51 карточка при цели 12, то есть добор не делал НИЧЕГО и не
сделал бы ещё месяц. А выдача устроена иначе: человеку показывают только то, чего он
ещё не видел, и этот личный запас тает на 2 карточки в день.

    владелец        видел 94 карточки  →  осталось 33  →  16 дней
    остальные 25    видели 1–44        →  осталось 44–51 → 22–25 дней

То есть общий счётчик говорил «всё хорошо» ровно тогда, когда у самого активного
человека до пустоты оставалось две недели. Он бы упёрся первым и получил алерт
«нечего выдать» — в день, когда карточки кончились, а не заранее.

Владелец 13.09.2026: «Зачем мне просто инфо, что пул почти пуст? Мне нужно, чтобы
автоматически закрывался пробел в заданиях. Автоматически».

Правило
───────
Цель добора считается не от банка, а от САМОГО БЕДНОГО активного человека: у каждого
должен быть запас непоказанных карточек минимум на MIN_RUNWAY_DAYS дней вперёд. Не
хватает — добираем столько, сколько не хватает ему, но не больше CAP за один прогон:
ночь не должна превращаться в многочасовой поход в словарь и в DWDS, а нехватка
закрывается за несколько ночей, потому что запас тает медленно (2 карточки в сутки).

Новая карточка поднимает запас СРАЗУ ВСЕМ: её не видел никто. Поэтому считать нужно
по одному человеку — самому бедному, — а не складывать нехватку по всем.
"""
from __future__ import annotations

# Запас непоказанных карточек, ниже которого добор обязан проснуться. Две недели —
# чтобы между «начали добирать» и «кончилось» оставался запас на несколько ночей,
# даже если DWDS молчит и за ночь проходит одно слово из пяти.
MIN_RUNWAY_DAYS = 14

# Потолок добора за один прогон. Каждая новая карточка — это поход в словарь и (если
# слова нет в кеше частот) запрос к DWDS. Двадцати хватает, чтобы закрыть недельную
# просадку за одну ночь, и мало, чтобы прогон растянулся на часы.
CAP_PER_RUN = 20

# Потолок по времени на один прогон добора. Дверь приёмки ходит к DWDS, и молчащая сеть
# стоит до 20 секунд на слово: без срока сорок попыток подряд дали бы тринадцать минут
# ожидания на одну карточку. Десять минут — верхняя граница ночной работы; недобранное
# доберётся следующей ночью, потому что запас тает на 2 карточки в сутки.
MAX_SECONDS_PER_RUN = 600


def refill_target(*, have: int, weakest_unseen: int | None, slots_per_day: int,
                  pool_target: int) -> int:
    """Сколько карточек должно быть в банке после этого прогона.

    have           — сколько неснятых карточек в банке сейчас;
    weakest_unseen — сколько карточек ещё не видел самый бедный активный человек;
                     None означает «активных получателей нет» (например, у нового
                     бота) — тогда работает прежняя цель по банку, и это не догадка,
                     а отсутствие людей, для которых считать запас;
    slots_per_day  — сколько анаграмм уходит человеку за сутки (берётся из расписания);
    pool_target    — прежняя цель по банку, снизу её не опускаем.
    """
    цель_по_банку = int(pool_target)
    if weakest_unseen is None:
        return цель_по_банку
    нужен_запас = MIN_RUNWAY_DAYS * max(1, int(slots_per_day))
    не_хватает = max(0, нужен_запас - int(weakest_unseen))
    return max(цель_по_банку, int(have) + min(не_хватает, CAP_PER_RUN))


def runway_days(weakest_unseen: int | None, slots_per_day: int) -> float | None:
    """На сколько дней хватит самому бедному человеку. None — активных получателей нет."""
    if weakest_unseen is None:
        return None
    return round(int(weakest_unseen) / max(1, int(slots_per_day)), 1)
