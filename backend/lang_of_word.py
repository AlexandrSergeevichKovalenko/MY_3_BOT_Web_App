"""
ОДИН ответчик на всё приложение: на каком языке лежит слово в этой карточке.

ЗАЧЕМ. Перепись 15.09.2026 нашла 43 места в бэкенде и 18 на фронте, где к содержимому
колонки `word_de` применяется НЕМЕЦКАЯ грамматика — артикль, род, падежи, немецкое
правило заглавной буквы, немецкий голос озвучки — и почти нигде перед этим не
спрашивают язык. Пока язык в базе один, это незаметно. В день, когда в ту же колонку
ляжет английское слово, каждое из этих мест начнёт врать:
    «die hard» → «die» покрасится как артикль женского рода;
    «Gift» (подарок) ночная задача перепишет в «das Gift» (яд);
    «the plan backfired» прочитают немецким голосом.

Поэтому вопрос задаётся ОДИН РАЗ и ОДНОЙ функцией. Копия этого правила в другом месте
означает, что однажды две копии разойдутся, и поймать это будет нечем.

⚠ ПОЧЕМУ НЕЛЬЗЯ СПРАШИВАТЬ «ЕСТЬ ЛИ de В ПАРЕ». Напрашивается простое условие
«source_lang='de' OR target_lang='de'», и оно уже написано в одном ночном актёре
(`german_form_warm.py`). Оно НЕВЕРНО: у будущей пары en→de немецкий — РОДНОЙ язык
человека, а изучаемое слово английское. Такое условие пропустит английское слово
в немецкую машину.

    карточка   что лежит в колонке слова
    ─────────  ─────────────────────────
    ru→de      немецкое     (родной ru, изучаемый de)
    de→ru      немецкое     (родной ru, изучаемый de)
    en→ru      АНГЛИЙСКОЕ   (родной ru, изучаемый en)
    en→de      АНГЛИЙСКОЕ   (родной de, изучаемый en)  ← «de в паре» здесь врёт

Правило простое: в колонке слова лежит НЕ РОДНАЯ сторона. Родную сторону называет
профиль человека, а не догадка.

⚠ «НЕ ЗНАЮ» — ЗАКОННЫЙ ОТВЕТ И ОН НЕ РАВЕН «НЕМЕЦКОМУ». Если родной язык не назван
или он не совпадает ни с одной стороной пары, функция возвращает None. Вызывающий
ОБЯЗАН в этом случае немецкое правило НЕ ПРИМЕНЯТЬ. Подставить «de» здесь значило бы
вернуть ровно ту ошибку, от которой этот модуль и заведён.
"""
from __future__ import annotations


def _норм(код: str | None) -> str:
    """Код языка к единому виду. Не строка — пустая строка, а не выдуманный язык."""
    return str(код).strip().lower() if isinstance(код, str) else ""


def язык_слова(
    *,
    source_lang: str | None,
    target_lang: str | None,
    native_lang: str | None,
) -> str | None:
    """Язык текста в колонке слова карточки (`word_de` и её отражения в разборе).

    Возвращает двухбуквенный код или None — «не знаю». None НЕ означает «немецкий».
    """
    s, t, n = _норм(source_lang), _норм(target_lang), _норм(native_lang)
    if not s or not t or not n:
        return None
    if s == t:
        return None                     # пара сама себе противоречит — не гадаем
    if n == s:
        return t                        # родная сторона — источник, значит слово в цели
    if n == t:
        return s                        # родная сторона — цель, значит слово в источнике
    return None                         # родной язык не участвует в паре — не знаем


def это_немецкое(
    *,
    source_lang: str | None,
    target_lang: str | None,
    native_lang: str | None,
) -> bool:
    """Можно ли применять немецкую грамматику к слову этой карточки.

    ТОЛЬКО явное «да». «Не знаю» — это «нет»: лучше не показать разбор, чем показать
    немецкий разбор английского слова.
    """
    return язык_слова(source_lang=source_lang, target_lang=target_lang,
                      native_lang=native_lang) == "de"
