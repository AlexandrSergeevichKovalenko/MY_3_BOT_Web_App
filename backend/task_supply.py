"""Хватает ли банка заданий: расчёт запаса и того, сколько дозаказать ночью.

Зачем этот файл существует
──────────────────────────
Целевые размеры банков заданы в коде константами «на глаз» (`CROSSWORD_POOL_TARGET=50`,
`REBUS_POOL_TARGET=20`, `ARTICLE_QUIZ_POOL_TARGET=30`) и с людьми никак не связаны.
Пока задание уходило всем сразу, этого хватало. С личной ротацией человек перестаёт
получать пройденное — значит у него банк однажды кончится, и надо заранее знать когда.

Закон роста (замер 14.08.2026)
──────────────────────────────
Разным людям МОЖНО в один день дать одно и то же задание — нельзя повторять одному и
тому же. Поэтому **размер банка почти не зависит от числа людей**: 13 человек или 3000 —
нужен примерно одинаковый банк. Зависит он от ВРЕМЕНИ: активный человек выбрасывает
задания навсегда, значит банк должен расти со скоростью расхода ОДНОГО самого активного
человека, а не умножаться на всех. Отсюда и весь расчёт ниже: считаем по самому
продвинутому, а не по среднему и не по сумме.

Почему не по буквально самому первому: один аномальный человек (например, владелец,
гоняющий тесты) завысил бы потребность для всех. Берём 95-й процентиль по глубине.
"""

# Держим запас не меньше месяца: месяц — это и запас прочности на праздники/отпуск
# генератора, и достаточный срок, чтобы владелец успел заметить отчёт и вмешаться.
TARGET_SUPPLY_DAYS = 30


def percentile(values: list, share: float) -> float:
    """Значение, ниже которого лежит `share` наблюдений. Пустой список — ноль."""
    xs = sorted(float(v) for v in (values or []))
    if not xs:
        return 0.0
    if len(xs) == 1:
        return xs[0]
    pos = max(0.0, min(1.0, float(share))) * (len(xs) - 1)
    low = int(pos)
    high = min(low + 1, len(xs) - 1)
    return xs[low] + (xs[high] - xs[low]) * (pos - low)


def supply_days(available: int, per_day: float) -> float:
    """На сколько дней хватит `available` заданий при расходе `per_day` в сутки.

    Расход ноль — значит человек эту игру не берёт вовсе; тогда запас бесконечен, и
    дозаказывать нечего. Отдаём большое число, а не деление на ноль.
    """
    rate = float(per_day or 0.0)
    if rate <= 0:
        return float("inf")
    return max(0, int(available or 0)) / rate


def shortfall(available: int, per_day: float,
              target_days: int = TARGET_SUPPLY_DAYS) -> int:
    """Сколько заданий дозаказать сегодня ночью, чтобы запас дотянул до `target_days`.

    Ноль означает «не генерировать ничего»: при 13 неглубоких пользователях запас
    огромный, и денег мы не тратим. Пополнение включится само, когда люди углубятся.
    """
    rate = float(per_day or 0.0)
    if rate <= 0:
        return 0
    need = int(round(rate * max(0, int(target_days))))
    return max(0, need - max(0, int(available or 0)))


def verdict(days: float) -> str:
    """Человеческая оценка запаса — для отчёта владельцу, не для кода."""
    if days == float("inf"):
        return "не расходуется"
    if days < 7:
        return "ДНО: меньше недели"
    if days < TARGET_SUPPLY_DAYS:
        return "мало: меньше месяца"
    if days < 90:
        return "норма"
    return "с запасом"
