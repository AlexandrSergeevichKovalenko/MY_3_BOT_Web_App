# -*- coding: utf-8 -*-
"""Счётчик пачек перевода субтитров: сколько раз модель вернула не то число строк.

Зачем счётчик, а не поиск по базе. Этот сдвиг СЛЕДА В ДАННЫХ НЕ ОСТАВЛЯЕТ: строки стоят
на своих местах, просто не те. Посчитать его постфактум нельзя — только поймать в момент
ответа. Поэтому число живёт здесь, копится по дням и показывается в `/subtitry` строкой 4.

Числа три, и они разные:
  • batches   — сколько пачек перевода мы вообще отправили;
  • mismatched — в скольких модель с первого раза вернула не то число строк;
  • refused   — в скольких она не попала и со второго раза, и пачка НЕ СОХРАНЕНА.

`refused` — это честное «не смогли», а не поломка: лучше не показать перевод куска, чем
навсегда привязать к репликам чужие строки.
"""
from __future__ import annotations

import logging

logger = logging.getLogger(__name__)


def record_batch(*, mismatched: bool, refused: bool) -> None:
    """Отметить одну пачку.

    Сбой записи счётчика НЕ имеет права утащить за собой перевод, ради которого всё
    затевалось, — но и молчать о нём нельзя: он идёт в журнал. Это ровно то единственное
    исключение, которое разрешено правилом ноль (побочная запись вокруг главной).
    """
    try:
        from backend.database import bump_subtitle_translate_stats
        bump_subtitle_translate_stats(mismatched=bool(mismatched), refused=bool(refused))
    except Exception:
        logger.exception("не удалось записать счётчик пачек перевода субтитров")


def mismatch_counters() -> dict:
    """{"total", "mismatched", "refused", "since"} за всё время наблюдения.

    Ошибку чтения НЕ глушим: отчёт, показавший ноль вместо «не смогли посчитать», врёт
    владельцу ровно в том месте, ради которого его завели.
    """
    from backend.database import subtitle_translate_stats
    return subtitle_translate_stats()
