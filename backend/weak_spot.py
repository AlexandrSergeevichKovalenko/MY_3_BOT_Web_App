"""Подбор заданий под слабые места человека: одна откалиброванная формула на всех.

Зачем этот файл существует
──────────────────────────
14.08.2026 в Wo-Fragen нашлась поломка калибровки: неизмеренному признаку давался вес
0.5, а измеренному — его доля ошибок. Замер на 200 000 розыгрышей показал, что при доле
ошибок 0.2 измеренное побеждало неизмеренное в 0% случаев, при 0.3 — в 2%. Живой человек
ошибается на 15-30%, поэтому «упор на мои ошибки» не включался ни у кого, кроме
безнадёжных случаев: у единственного человека, прошедшего порог, доля заданий на
измеренные признаки вышла 0.000 против 0.231 при случайной выдаче — перекос шёл в
ОБРАТНУЮ сторону.

Здесь та же формула вынесена отдельно, чтобы следующий тренажёр не повторил ошибку
заново, а взял готовое и проверенное.
"""

import random

# Ниже трёх ответов доля ошибок — не замер, а шум: одна промашка даёт 100%.
MIN_ATTEMPTS = 3
# Вес того, что про человека ещё НЕ измерено: ВЫШЕ освоенного, но НИЖЕ всего, где он
# ошибается чаще трети.
UNMEASURED_WEIGHT = 0.32
# Шум, чтобы верхушка колоды не была одной и той же пачку за пачкой.
PICK_NOISE = 0.20


def measured_weight(stats: dict, key: str) -> float:
    """Доля ошибок по одному признаку; где мерить ещё нечего — средний вес."""
    stat = (stats or {}).get(key) or {}
    attempts = int(stat.get("attempts") or 0)
    if attempts < MIN_ATTEMPTS:
        return UNMEASURED_WEIGHT
    return 1.0 - (int(stat.get("correct") or 0) / attempts)


def order_by_weakness(items: list, stats: dict, key_of) -> list:
    """Отсортировать задания так, чтобы слабое шло чаще. `key_of` достаёт признак."""
    def score(item):
        return measured_weight(stats, str(key_of(item) or "")) + random.random() * PICK_NOISE
    return sorted(list(items or []), key=score, reverse=True)
