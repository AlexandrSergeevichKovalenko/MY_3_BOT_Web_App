"""Приёмка слов для ребуса по ходовости. Решение владельца 01.09.2026.

Повод
─────
Владельцу пришёл ребус «Eieruhr» — кухонный таймер для варки яиц. Слово настоящее
(есть в нашем базовом словаре), но по корпусу DWDS встречается 120 раз на миллиард
против 45 509 у Bahnhof: в 380 раз реже. Владелец слово не узнал и спросил, много ли
такого. Прогон всех 338 карточек банка через DWDS 01.09.2026:

    из 77 карточек, которые выдаются людям:
        19 ходовых (> 3 000 на млрд), 29 нормальных (1 000 – 3 000),
        17 нечастых (300 – 1 000), 12 редких (< 300)
    хвост, который человек видит: Katzenkorb 47, Tigerfell 48, Suppenkelle 68,
        Hundehaus 77, Hammerhai 78, Eieruhr 120, Schwertfisch 128, Hahnenkamm 147,
        Goldring 159, Vogelkäfig 180, Salatschüssel 241, Haarbürste 270
    прямые выдумки модели (все УЖЕ сняты, людям не идут): Geldbeutelverschluss 0,0
        (застёжка кошелька), Sandsschloss 0,0 (ещё и опечатка), Weckerknopf 0,1,
        Schneemannhut 0,2, Steuerflasche 0,4 («бутылка для измерения налога»)

Что решил владелец
──────────────────
1. Накопленное НЕ удаляем — правило действует только на пополнение.
2. Порог — 300 вхождений на миллиард.
3. DWDS не ответил — слово НЕ пускаем, переспрашиваем ночью. «Не знаем» не равно
   «годится».

Почему порог именно 300, а не выше
──────────────────────────────────
DWDS собран из письменных текстов и занижает бытовые предметы, а рисуются на
картинках именно они: сковорода 602, яичница-глазунья 754, кофейная чашка 917,
курятник 731, улей 903. Порог 1 000 выкинул бы их все — 29 из 77. Ровно эта же
оговорка записана в приёмке кроссворда (`backend/crossword_word_gate.py`) по
разбору 31.07.2026. Поднимать порог без нового замера нельзя.
"""
from __future__ import annotations

import logging

logger = logging.getLogger(__name__)

# Вхождений на миллиард слов корпуса DWDS. Решение владельца 01.09.2026.
MIN_PER_BILLION = 300.0


def judge_rebus_word(word: str, *, allow_network: bool = True) -> tuple[bool, str]:
    """(годится, причина). Причина непустая всегда, когда не годится.

    Три исхода, и они РАЗНЫЕ:
      • частота известна и не ниже порога → пускаем;
      • частота известна и ниже порога    → не пускаем, слово редкое;
      • частоты нет                        → не пускаем, но это «не знаем»,
        а не приговор: слово ждёт ночного переспроса.
    """
    from backend.dwds_frequency import word_per_billion

    word = str(word or "").strip()
    if not word:
        return False, "пустое слово"

    ppb = word_per_billion(word, allow_network=allow_network)
    if ppb is None:
        return False, f"частота неизвестна — DWDS не ответил про «{word}», переспросим ночью"
    if ppb < MIN_PER_BILLION:
        return False, (f"слишком редкое: «{word}» встречается {ppb:.0f} раз на миллиард, "
                       f"порог {MIN_PER_BILLION:.0f}")
    return True, ""
