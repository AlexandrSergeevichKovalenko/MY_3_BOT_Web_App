def _e(s: str) -> str:
    return html.escape(str(s or ""))


# Runtime-discovered admin commands that are NOT (yet) hand-curated in a topic above.
# Populated at bot startup by introspecting the registered CommandHandlers (see
# sync_discovered_admin_commands in bot_3.py) so a newly added admin command shows up in
# the «🛠 Команды админа» palette automatically — with its docstring as a provisional
# description — instead of silently missing until someone edits this file.
_EXTRA_TOPICS: list[tuple[str, str, list[dict]]] = []


def register_discovered_topic(tid: str, title: str, cmds: list[dict]) -> None:
    """Add/replace the synthetic topic that holds auto-discovered (uncatalogued) commands.
    Idempotent by topic id, so re-running discovery just refreshes it."""
    global _EXTRA_TOPICS
    _EXTRA_TOPICS = [t for t in _EXTRA_TOPICS if t[0] != tid]
    if cmds:
        _EXTRA_TOPICS.append((tid, title, list(cmds)))


# Approved runtime descriptions loaded from the DB (slug -> {desc, args, example,
# topic_id}), set by set_db_descriptions() at startup and after each /describe_new save.
# Merged into their topic by all_topics() so a described command leaves «🆕 Новые».
_DB_DESCRIPTIONS: dict[str, dict] = {}


def set_db_descriptions(mapping: dict) -> None:
    """Replace the DB-backed description set (slug -> {desc, args, example, topic_id})."""
    global _DB_DESCRIPTIONS
    _DB_DESCRIPTIONS = dict(mapping or {})


def db_described_names() -> set[str]:
    """Command slugs that have an approved DB description (so discovery can skip them)."""
    return set(_DB_DESCRIPTIONS.keys())


def all_topics() -> list[tuple[str, str, list[dict]]]:
    """Curated topics + DB-described commands merged into their topic + runtime-discovered
    («🆕 Новые») ones — the full palette to render."""
    curated = catalog_command_names()
    # Fresh copies of the curated command lists so we can append without mutating the source.
    topics = [(tid, title, list(cmds)) for (tid, title, cmds) in ADMIN_COMMAND_TOPICS]
    by_id = {tid: cmds for (tid, _title, cmds) in topics}
    for slug, d in (_DB_DESCRIPTIONS or {}).items():
        if slug in curated:
            continue  # code catalog is authoritative for hand-listed commands
        tid = str(d.get("topic_id") or "misc")
        if tid not in by_id:
            tid = "misc"
        cmds = by_id.get(tid)
        if cmds is None:
            continue
        if any(str(c.get("cmd") or "").lstrip("/") == slug for c in cmds):
            continue
        cmds.append({
            "cmd": f"/{slug}",
            "desc": d.get("desc") or "",
            "args": d.get("args") or "нет аргументов",
            "example": d.get("example") or f"/{slug}",
        })
    return topics + list(_EXTRA_TOPICS)


def catalog_command_names() -> set[str]:
    """Every command slug already curated in ADMIN_COMMAND_TOPICS (no leading slash)."""
    out: set[str] = set()
    for _tid, _title, cmds in ADMIN_COMMAND_TOPICS:
        for c in cmds:
            out.add(str(c.get("cmd") or "").lstrip("/").strip())
    return out


def topic_by_id(topic_id: str):
    for tid, title, cmds in all_topics():
        if tid == topic_id:
            return tid, title, cmds
    return None


def render_topics_overview() -> str:
    """Intro text shown above the topic buttons."""
    topics = all_topics()
    total = sum(len(cmds) for _, _, cmds in topics)
    return (
        "🛠 <b>Команды администратора</b>\n"
        f"Всего команд: <b>{total}</b> в {len(topics)} темах.\n\n"
        "Выберите тему — пришлю список команд с описанием и параметрами."
    )


def render_topic(topic_id: str) -> str | None:
    """Full HTML text for one topic: every command with desc, args, example."""
    found = topic_by_id(topic_id)
    if not found:
        return None
    _, title, cmds = found
    lines = [f"<b>{_e(title)}</b>", ""]
    for o in cmds:
        lines.append(f"<b>{_e(o['cmd'])}</b>")
        lines.append(_e(o["desc"]))
        lines.append(f"<i>Аргументы:</i> {_e(o['args'])}")
        lines.append(f"<i>Пример:</i> <code>{_e(o['example'])}</code>")
        lines.append("")
    return "\n".join(lines).rstrip()


def split_for_telegram(text: str, limit: int = 3800) -> list[str]:
    """Split a long HTML message on blank lines so no chunk exceeds Telegram's cap."""
    if len(text) <= limit:
        return [text]
    chunks: list[str] = []
    cur = ""
    for block in text.split("\n\n"):
        candidate = (cur + "\n\n" + block) if cur else block
        if len(candidate) > limit and cur:
            chunks.append(cur)
            cur = block
        else:
            cur = candidate
    if cur:
        chunks.append(cur)
    return chunks
