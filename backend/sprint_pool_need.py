# -*- coding: utf-8 -*-
"""Нужно ли ночью добирать банк синонимов — одно правило, без базы.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ
────────────────────
Решение «заказывать или нет» жило внутри ночной задачи и проверялось только глазами.
Замер 14.09.2026 показал, чем это кончилось: банк синонимов ровно равнялся цели (30 при
цели 30), задача видела «отставания нет» и не заказывала НИЧЕГО — а свободным для
тренировки было ОДНО слово из тридцати. Капельная выдача каждый день не находила
отдохнувшего и уходила в запасной ход с кулдауном ноль: правило «21 день» по факту не
соблюдалось, у синонимов 28 повторов из 34 пришли раньше срока (средний промежуток
13,9 дня вместо 21), и увидеть это было нечем.

Правило чистое, поэтому проверяется тестами, а не живой базой (тот же приём, что в
backend/task_rotation.py).

ДВОЕ ЧАСОВ, И ЭТО ГЛАВНОЕ
─────────────────────────
Спринт и тренировка берут слова из ОДНОГО банка, но отдых считают по РАЗНЫМ полям:
спринт по `last_sent_at`, тренировка по `trainer_last_sent_at` (и берёт только
собранные, trainer_ready). Часы идут независимо, поэтому «свободно» у них разное:
замер 14.09.2026 — синонимы 12 против 1, антонимы 35 против 6. Решать надо по ХУДШЕМУ
из двух: пустой у одного потребителя банк не лечится запасом у другого.
"""

from __future__ import annotations

import math
from dataclasses import dataclass


@dataclass(frozen=True)
class TopupDecision:
    need: bool          # заказывать ли вообще
    want: int           # сколько заказать этой ночью (уже с потолком)
    floor_free: int     # порог свободного запаса, от которого считали
    gap_bank: int       # отставание банка от цели
    gap_free: int       # нехватка свободного запаса у худшего потребителя
    reason: str         # человеческими словами, для лога


def decide_topup(*, bank: int, target: int, per_day: float,
                 free_sprint: int, free_trainer: int,
                 rail_span_days: int, cap_per_night: int) -> TopupDecision:
    """Заказывать ли слова и сколько.

    Два независимых повода, и хватает любого:
      1. банк меньше цели — классическое отставание;
      2. СВОБОДНОГО запаса у худшего потребителя меньше, чем на длину рельса.

    Порог `floor_free` — не круглое число: это длина рельса, три дня от тренировки до
    спринта, умноженная на суточный расход. Меньше — цепочка рвётся у ближайшего же
    слова, и человек получает повтор раньше срока вместо нового.
    """
    worst_free = min(int(free_sprint), int(free_trainer))
    floor_free = max(1, math.ceil(max(0.0, float(per_day)) * max(1, int(rail_span_days))))
    gap_bank = max(0, int(target) - int(bank))
    gap_free = max(0, floor_free - worst_free)
    need = gap_bank > 0 or gap_free > 0
    # Берём БОЛЬШЕЕ из двух, а не сумму: это одна и та же нехватка, померенная с двух
    # сторон, и заказывать её дважды значит платить модели за лишние карточки.
    want = min(max(1, int(cap_per_night)), max(gap_bank, gap_free)) if need else 0
    if not need:
        reason = "банк на цели, свободного запаса хватает"
    elif gap_free > gap_bank:
        reason = (f"свободных всего {worst_free} при пороге {floor_free} "
                  f"(спринт {free_sprint}, тренировка {free_trainer})")
    else:
        reason = f"банк {bank} при цели {target}"
    return TopupDecision(need=need, want=want, floor_free=floor_free,
                         gap_bank=gap_bank, gap_free=gap_free, reason=reason)
