# -*- coding: utf-8 -*-
"""Правило личной ротации заданий: кому какое задание из общего банка.

Зачем этот файл существует
──────────────────────────
Замер 14.08.2026: правильность ответов пишется в девяти таблицах, а при следующей выдаче
её читают всего четыре места. Поиск условий вида «показать то, что человек завалил» в
выборках заданий дал ноль совпадений. Для человека это выглядит так: он не угадал слово в
кроссворде, программа честно это записала — и завтра кроссворд соберётся из случайных
слов, а то самое слово может не попасться ему больше никогда.

Второе: одно задание выбирается ОДИН раз до цикла рассылки и уходит всем сразу, хотя сам
цикл давно идёт по людям и каждому шлёт отдельное сообщение.

Здесь лежит ОДНО правило отбора на все тренажёры, и лежит оно без базы: чистые функции
проверяются тестами и не зависят от живых данных.

Что важно не перепутать
───────────────────────
Заваленное задание пула возвращает очередь работы над ошибками (`bt_3_aufgabe_mistakes`,
лестница 1/3/7/16 дней) — это её работа, и дублировать её здесь нельзя. Ротация занимается
другим: следит, чтобы человек не получал по второму разу то, что уже решил.

Но очередь ошибок покрывает не все игры: кроссворда и анаграммы в ней нет ни одной строки
(замер 24.08.2026). Для них заваленное задание возвращает сама ротация — по короткой
лестнице `WRONG_LADDER_DAYS`. Кому она положена, решает `WRONG_LADDER_BY_KIND`.

Расход банка считается по СДАЧАМ, а не по отправкам (решение владельца 24.08.2026):
отправленное, но не открытое задание ничего не израсходовало и вернётся человеку снова.

Закон роста банка (замер 14.08.2026)
────────────────────────────────────
Разным людям МОЖНО в один день дать одно и то же задание — запрещено повторять одному и
тому же. Поэтому размер банка почти не зависит от числа людей: 13 человек или 3000 —
нужен примерно одинаковый банк. Зависит он от ВРЕМЕНИ: человек, играющий каждый день,
выбрасывает задания навсегда, значит банк должен расти со скоростью расхода одного самого
активного человека, а не умножаться на всех.
"""

from datetime import datetime, timedelta

# Решил верно один раз — вернуть через 90 дней; второй — через 120; третий — никогда.
# Решение владельца 14.08.2026: «глупо показывать мне то, что я правильно решил».
LADDER_DAYS = (90, 120)

# Сдал, но неверно — вернуть через 7 дней, снова неверно — через 14, потом через 30.
# Решение владельца 24.08.2026.
#
# Лестница включается НЕ ВСЕМ, и вот почему. У заданий пула неверный ответ вправду
# подхватывает работа над ошибками (`bt_3_aufgabe_mistakes`, лестница 1/3/7/16): замер
# 24.08.2026 — 46 живых строк форматов cloze/satzbau/error/transform, плюс artikel 238 и
# wofrage 109. А кроссвордов и анаграмм в этой очереди НОЛЬ строк: их неугаданное слово
# не попадает никуда, и до 24.08.2026 неверно решённый кроссворд не закрывался для
# человека вообще (`next_eligible_at` оставался пустым) — его придерживал только общий
# отдых карточки, который тем же решением снят. Поэтому лестницу получают именно те
# виды, у которых своего механизма возврата нет; кому её давать, решает
# `WRONG_LADDER_BY_KIND` в backend/database.py, а не этот файл.
WRONG_LADDER_DAYS = (7, 14, 30)


def next_state(*, seen_count: int, correct_count: int, is_correct: bool,
               now: datetime, wrong_ladder: tuple = ()) -> dict:
    """Новое состояние задания для человека после его ответа.

    `wrong_ladder` пустая — поведение прежнее: неверный ответ лестницу не двигает
    (так живут виды, у которых повтором заведует работа над ошибками).
    """
    seen = int(seen_count or 0) + 1
    correct = int(correct_count or 0) + (1 if is_correct else 0)
    if not is_correct:
        if not wrong_ladder:
            # Повтором заведует работа над ошибками — здесь ничего не держим.
            return {"seen_count": seen, "correct_count": correct,
                    "next_eligible_at": None, "retired_at": None}
        # Шаг лестницы — по числу неверных сдач; отдельной колонки для этого не нужно.
        # Дальше последней ступени срок не растёт и «навсегда» не наступает: человек
        # задание так и не решил, отнимать его у него насовсем неправильно.
        wrong = max(1, seen - correct)
        days = wrong_ladder[min(wrong, len(wrong_ladder)) - 1]
        return {"seen_count": seen, "correct_count": correct,
                "next_eligible_at": now + timedelta(days=int(days)),
                "retired_at": None}
    if correct > len(LADDER_DAYS):
        return {"seen_count": seen, "correct_count": correct,
                "next_eligible_at": None, "retired_at": now}
    return {"seen_count": seen, "correct_count": correct,
            "next_eligible_at": now + timedelta(days=LADDER_DAYS[correct - 1]),
            "retired_at": None}


def _bucket(state: dict | None, now: datetime) -> tuple:
    """Ключ сортировки: (корзина, давность). Меньше — раньше в выдаче."""
    if not state:
        return (0, now)                                   # не видел — вперёд
    due = state.get("next_eligible_at")
    last = state.get("last_seen_at") or now
    if due is None or due <= now:
        return (1, last)                                  # срок вышел, самое давнее вперёд
    return (2, last)                                      # срок не вышел — в хвост


def order_candidates(candidates: list[dict], state_by_key: dict,
                     now: datetime) -> list[dict]:
    """Отсортировать кандидатов под конкретного человека.

    Выброшенные навсегда исключаются — но если после этого не осталось ничего, они
    возвращаются обратно: пустой экран человеку недопустим, лучше повтор.
    """
    alive, retired = [], []
    for c in candidates:
        st = (state_by_key or {}).get(str(c.get("task_key") or ""))
        (retired if (st or {}).get("retired_at") else alive).append(c)
    pool = alive or retired
    return sorted(pool, key=lambda c: _bucket(
        (state_by_key or {}).get(str(c.get("task_key") or "")), now))
