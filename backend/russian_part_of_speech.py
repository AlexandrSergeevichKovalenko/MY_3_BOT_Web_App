# -*- coding: utf-8 -*-
"""Часть речи РУССКОГО перевода — второй голос о том, чем является немецкое слово.

Зачем этот модуль (решение владельца 24–25.08.2026)
───────────────────────────────────────────────────
Владелец открыл карточку «die Mies» — «Паршивый» — с выдуманными значениями про
неудачников и спросил, откуда это берётся.

Корень — ЗАГЛАВНАЯ БУКВА. Человек ищет слово, и с клавиатуры оно приходит с заглавной:
это первое и единственное слово запроса. В немецком заглавная означает существительное,
поэтому «reif» («зрелый») уезжало в базу как «Reif», справочник честно отвечал про
существительное «der Reif» (иней, обруч), а модель сочиняла под него смыслы и примеры.
Так же появились «die Rein» («чистый»), «das Wetten» («держать пари»), «der Simpel»
(«простой»). Замер 25.08.2026: 111 таких заголовков.

КАК ЭТО РЕШЕНО У ЛИДЕРОВ (разбор 25.08.2026, требование CLAUDE.md — сперва чужое решение)
    DWDS      держит «Reif» и «reif» как ДВЕ РАЗНЫЕ статьи по разным адресам
              (/wb/Reif и /wb/reif), у каждой явная помета «Substantiv (Maskulinum)».
              Омонимы одного написания — вкладками на одной странице.
    dict.cc   регистр запроса НЕ УЧИТЫВАЕТ вовсе: «Reif» и «reif» дают одну выдачу,
              где рядом стоят «reif | reifer | am reifsten  ADJ» и «der Reif | die Reife
              NOUN». Класс слова у них — ОТДЕЛЬНОЕ ПОЛЕ в данных, а не следствие
              написания.
    Общее     ни один не решает за человека. Слово с двумя частями речи — это две
              статьи рядом, выбирает человек.

У нас же заглавная буква решала за человека молча — и решала неверно.

ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ. Русский перевод писал человек, и он не врёт: «Нос» —
существительное, «Зрелый» — прилагательное, «Грести» — глагол. Спрашиваем часть речи у
русской стороны и получаем ВТОРОЙ ГОЛОС о немецком слове.

ИСТОЧНИК: pymorphy3 — словарный морфологический разбор русского. MIT, ~13 МБ, работает
ОФЛАЙН и ПО ОДНОМУ СЛОВУ, без контекста. Это ровно наш случай: контекста у перевода нет.
Русская модель spaCy сюда не годится — она разбирает слово в предложении, а её
собственные леммы всё равно берутся из pymorphy3.

ПОЧЕМУ НЕ РЕГУЛЯРКА ПО ОКОНЧАНИЮ. Пробовал 24.08.2026, развалилось на живых данных:
    «Последовательность»  кончается на «ть» → счёл глаголом
    «Ясность»             то же
    «Микроволновая печь»  «печь» кончается на «чь» → глагол
    «Срок полномочий»     «полномочий» на «ий» → прилагательное
Все четыре — существительные. Окончание слова НЕ является частью речи.

СПОРНОЕ ОСТАЁТСЯ СПОРНЫМ. «Простой» — и прилагательное, и существительное («простой
оборудования»). «Правда» — и существительное, и частица. Такие слова получают вердикт
AMBIGUOUS, и по ним НЕ ПРИНИМАЕТСЯ никакого решения: выбирать за человека между двумя
верными разборами значит угадывать.
"""
from __future__ import annotations

import logging
import re
import threading

logger = logging.getLogger(__name__)

NOUN = "существительное"
ADJECTIVE = "прилагательное"
VERB = "глагол"
ADVERB = "наречие"
OTHER = "другое"
AMBIGUOUS = "спорно"
UNKNOWN = "не знаем"

# Разбор грузится один раз на процесс: словари pymorphy3 весят ~13 МБ и открываются
# около секунды. Второй разбор в том же процессе — лишняя секунда и лишняя память.
_analyzer = None
_analyzer_lock = threading.Lock()
_analyzer_failed = False

_CYRILLIC_WORD = re.compile(r"^[А-Яа-яЁё-]+$")

# Метки pymorphy3 → наши имена. Список закрытый: всё, чего здесь нет, — «другое».
_TAGS = {
    "NOUN": NOUN,
    "ADJF": ADJECTIVE, "ADJS": ADJECTIVE, "PRTF": ADJECTIVE, "PRTS": ADJECTIVE,
    "INFN": VERB, "VERB": VERB, "GRND": VERB,
    "ADVB": ADVERB,
}


def _get_analyzer():
    """Разбор pymorphy3 или None, если библиотеки нет.

    Отсутствие библиотеки — НЕ повод падать и НЕ повод угадывать: вызывающий получит
    «не знаем» и оставит запись как есть. Молчание честнее выдумки.
    """
    global _analyzer, _analyzer_failed
    if _analyzer is not None or _analyzer_failed:
        return _analyzer
    with _analyzer_lock:
        if _analyzer is not None or _analyzer_failed:
            return _analyzer
        try:
            import pymorphy3
            _analyzer = pymorphy3.MorphAnalyzer()
        except Exception:
            _analyzer_failed = True
            logger.warning("русская часть речи: pymorphy3 недоступен", exc_info=True)
    return _analyzer


def part_of_speech(text: str) -> str:
    """Часть речи русского слова: NOUN / ADJECTIVE / VERB / ADVERB / OTHER /
    AMBIGUOUS / UNKNOWN.

    Спрашивать имеет смысл ОДНО слово. Многословный перевод («держать пари», «в стороне,
    вдали») — это не слово, а оборот, и часть речи у него не определяется одним разбором:
    возвращаем UNKNOWN, пусть решает человек.
    """
    value = str(text or "").strip()
    if not value or not _CYRILLIC_WORD.match(value):
        return UNKNOWN

    analyzer = _get_analyzer()
    if analyzer is None:
        return UNKNOWN
    try:
        parses = analyzer.parse(value)
    except Exception:
        logger.warning("русская часть речи: разбор упал на «%s»", value, exc_info=True)
        return UNKNOWN
    if not parses:
        return UNKNOWN

    top = _TAGS.get(str(parses[0].tag.POS or ""), OTHER)
    all_kinds = {_TAGS.get(str(p.tag.POS or ""), OTHER) for p in parses}
    if top != NOUN and NOUN in all_kinds:
        # «Простой» — и прилагательное, и существительное. «Правда» — и существительное,
        # и частица. Выбирать за человека между двумя ВЕРНЫМИ разборами нельзя.
        return AMBIGUOUS
    return top


def proves_a_noun(text: str) -> bool:
    """Русская сторона ДОКАЗЫВАЕТ, что немецкое слово — существительное.

    Доказывает — значит разбор однозначен. «Спорно» и «не знаем» доказательством не
    являются: это отсутствие ответа, а не ответ «нет».
    """
    return part_of_speech(text) == NOUN


def proves_not_a_noun(text: str) -> bool:
    """Русская сторона ДОКАЗЫВАЕТ, что немецкое слово НЕ существительное.

    Нужно отдельной функцией, а не отрицанием предыдущей: «не доказано, что да» и
    «доказано, что нет» — разные вещи, и путать их значит чинить по догадке.
    """
    return part_of_speech(text) in (ADJECTIVE, VERB, ADVERB)
