# -*- coding: utf-8 -*-
"""Довезти приговоры двери слова ДО ДАННЫХ. Сухой прогон по умолчанию.

ЗАЧЕМ ЭТОТ СКРИПТ ПОЯВИЛСЯ
──────────────────────────
Владелец 25.08.2026: «Применяй 23 приговора». Замер показал, что их к тому моменту
уже 47, и ни один не доехал до данных: 38 «исправлено» и 9 «не слово» лежали в
`bt_3_word_check` вынесенными и неприменёнными.

Дыра, из-за которой это возможно, — в ночном проходе `warm_word_gate`. Он берёт слова
запросом `NOT EXISTS (SELECT 1 FROM bt_3_word_check WHERE w.asked = u.lemma)`, то есть
ТОЛЬКО те, которых он ещё не видел. Приговор выносится и тут же ложится в кеш — и с
этой секунды слово для ночного прохода больше не существует. Применение идёт следом,
в том же витке цикла; сорвалось оно (обрыв, исключение, перезапуск) — второй попытки
не будет НИКОГДА. Молча.

Поэтому здесь появилась отметка `applied_at`: вынесенный приговор и приговор,
доехавший до данных, — разные состояния, и различать их обязана база, а не память.

⛔ КЕШУ ВЕРИТЬ НЕЛЬЗЯ — ЭТО ГЛАВНОЕ ПРАВИЛО ЭТОГО СКРИПТА
────────────────────────────────────────────────────────
Приговор мог быть вынесен дверью, которую с тех пор ПОЧИНИЛИ. Проверка 25.08.2026:
из 38 приговоров «исправлено» СЕМЬ оказались ядовитыми — сегодняшняя дверь говорит по
ним «подтверждено, не трогать»:

    aber → Aber      gehen → Gehen      heulen → Heulen      pfeifen → Pfeifen
    schwimmen → Schwimmen    vier → Vier    wenn → Wenn

Все семь родились из одного дефекта, закрытого 23.08: справочник родов знает «das Gehen»
(субстантивированный инфинитив) и «die Vier» (цифра), и дешёвая ступень объявляла
существительным глагол «gehen» и числительное «vier». Применить их значило подменить
человеку слово: он учил «идти», а получил бы «ходьбу». Живут эти семь не в вакууме —
«gehen», «heulen», «pfeifen», «vier» лежат в общем пуле и в личных карточках.

Поэтому каждый приговор ПЕРЕСПРАШИВАЕТСЯ у живой двери, и применяется только тот, с
которым она согласна сегодня. Расхождение — вчерашний приговор ПЕРЕПИСЫВАЕТСЯ сегодняшним
и идёт в работу этим же заходом (снимать и ждать очереди нельзя: ночной проход берёт по
150 слов по свежести правки, и слово с 19 августа могло не всплыть месяцами).

ЧТО ДЕЛАЕТСЯ С ЧЕМ
──────────────────
    исправлено, цели в словаре НЕТ   → переименование во всех трёх хранилищах:
                                       retitle_unit (написание, лемма, ключ, вид записи)
                                       + spread_correction_everywhere (пул, карточки,
                                       разбор внутри карточки)
    исправлено, цель в словаре ЕСТЬ  → СКЛЕЙКА, а не переименование: иначе в базе два
                                       одинаковых слова. Зовём общую merge_unit_into —
                                       поверхности, карточки, источники и связи
                                       переезжают, человек своё слово не теряет.
    не слово                         → снимаем из НАШИХ данных: общий пул и строка
                                       словаря. Общий пул это кеш поиска, не чьи-то
                                       данные, — его чистить безопасно.
    ⚠ личная карточка человека       → НЕ ТРОГАЕМ НИКОГДА, даже если слово мусорное.
                                       Это его данные. Такие случаи печатаются числом
                                       и уходят владельцу с кнопками.

ПОЧЕМУ НЕ «УДАЛИТЬ СТРОКУ». На строку словаря ссылаются восемь таблиц (проверено
19.08.2026). Снятие идёт через ту же merge_unit_into, что и склейка, — она переносит
всё, что можно перенести, и только потом снимает строку.

ЗАПУСК РУКАМИ — scripts/word_gate_apply_verdicts.py (сухой прогон по умолчанию).
НОЧЬЮ — из того же актёра, что гоняет саму дверь (backend/background_jobs.py):
приговор, не доехавший до данных, подбирается на следующую ночь сам.
"""
from __future__ import annotations

import logging
import time

from backend.database import get_db_connection_context


# Пауза между переспросами. 4 c оказалось мало: дверь спрашивает справочник пачкой из
# девяти кандидатов, и прогон 25.08.2026 поймал HTTP 429 на седьмом слове. Отказ по
# частоте НЕОТЛИЧИМ от «слова нет» — то есть слишком быстрый темп не замедляет работу,
# а портит ответ.
ПАУЗА_СЕК = 10.0


def _единица(cur, слово: str) -> int | None:
    cur.execute("SELECT id FROM bt_3_lex_units WHERE lang='de' AND lower(lemma)=lower(%s) "
                "ORDER BY id LIMIT 1;", (слово,))
    строка = cur.fetchone()
    return int(строка[0]) if строка else None


def _личных_карточек(cur, слово: str) -> int:
    cur.execute("""SELECT count(*) FROM bt_3_webapp_dictionary_queries
                    WHERE lower(word_de)=lower(%s) OR lower(translation_de)=lower(%s);""",
                (слово, слово))
    return int(cur.fetchone()[0])


def _в_пуле(cur, слово: str) -> int:
    cur.execute("""SELECT count(*) FROM bt_3_dictionary_entries
                    WHERE lower(word_de)=lower(%s) OR lower(translation_de)=lower(%s);""",
                (слово, слово))
    return int(cur.fetchone()[0])


def _неприменённые() -> list[tuple]:
    """Короткое соединение: взять список и сразу отпустить.

    ⚠ Соединение НЕ держим открытым на время переспроса. Первый вариант этого скрипта
    брал курсор и с ним же ходил в справочник по 47 словам с паузой 10 c — через восемь
    минут PgBouncer закрыл соединение, и прогон упал на середине списка («server closed
    the connection unexpectedly», 25.08.2026). Сеть и база не смешиваются в одном
    держателе: сначала читаем, потом спрашиваем, потом пишем.
    """
    from backend.german_word_gate import REPAIRED, NOT_A_WORD
    with get_db_connection_context() as conn:
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute("""SELECT asked, text, status, pos FROM bt_3_word_check
                            WHERE status IN (%s, %s) AND applied_at IS NULL
                            ORDER BY status, asked;""", (REPAIRED, NOT_A_WORD))
            return list(cur.fetchall() or [])


def переспросить(приговоры: list[tuple], *, переспрашивать: bool) -> list[dict]:
    """Сверить каждый приговор с ЖИВОЙ дверью. Без базы — только сеть."""
    from backend.german_word_gate import _decide

    шаги = []
    for спрошено, было_текст, было_статус, была_часть_речи in приговоры:
        шаг = {"спрошено": спрошено, "было": было_текст, "статус": было_статус}
        if not переспрашивать:
            шаг["цель"] = было_текст
            шаги.append(шаг)
            continue
        сейчас = _decide(спрошено, pos_hint=была_часть_речи or "",
                         allow_network=True, allow_model=True)
        time.sleep(ПАУЗА_СЕК)
        источник = str(сейчас.get("source") or "")
        if источник in ("справочник молчал", "второй справочник молчал",
                        "не спрашивали справочник", "модель не спрашивали"):
            # Молчание источника — НЕ ответ. Ни применять, ни снимать приговор нельзя:
            # мы просто не знаем. Придём в следующий раз.
            шаг["действие"] = "источник молчал — отложено"
            шаги.append(шаг)
            continue
        стало_статус = str(сейчас.get("status") or "")
        стало_текст = str(сейчас.get("text") or "").strip()

        # ПРИГОВОР УСТАРЕЛ — ЕГО ПЕРЕПИСЫВАЕТ СЕГОДНЯШНИЙ, а не снимает.
        #
        # Первый вариант просто удалял строку и надеялся, что слово вернётся в общую
        # очередь. Надежда пустая: ночной проход берёт по 150 слов, отсортированных по
        # свежести правки, и слово с 19 августа могло не всплыть месяцами. Получался
        # тот самый мёртвый список — только теперь пустой.
        #
        # Пишем сегодняшний ответ на место вчерашнего, `applied_at` оставляем пустым —
        # и дальше он идёт в работу этим же заходом, наравне со всеми.
        if стало_статус != было_статус or стало_текст != (было_текст or "").strip():
            шаг["переписан"] = f"было {было_статус} «{было_текст}» → стало " \
                               f"{стало_статус} «{стало_текст}»"
            _переписать_приговор(спрошено, сейчас)
            шаг["статус"] = стало_статус
        шаг["цель"] = стало_текст
        шаги.append(шаг)
    return шаги


def _переписать_приговор(спрошено: str, вердикт: dict) -> None:
    """Положить сегодняшний ответ двери на место вчерашнего. `applied_at` не трогаем."""
    with get_db_connection_context() as conn:
        with conn.cursor() as cur:
            cur.execute("""UPDATE bt_3_word_check
                              SET text=%s, status=%s, pos=%s, source=%s, note=%s,
                                  checked_at=NOW(), reviewed=FALSE
                            WHERE asked=%s;""",
                        (вердикт.get("text") or "", вердикт.get("status") or "",
                         вердикт.get("pos") or "", вердикт.get("source") or "",
                         вердикт.get("note") or "", спрошено))
        conn.commit()
    logging.info("применение приговоров: %r переписан на %r/%r",
                 спрошено, вердикт.get("status"), вердикт.get("text"))


def собрать_план(cur, шаги: list[dict]) -> list[dict]:
    """Чем каждый переспрошенный приговор оборачивается в данных."""
    from backend.german_word_gate import CONFIRMED, NOT_A_WORD, UNCONFIRMED

    план = []
    for шаг in шаги:
        if шаг.get("действие"):
            план.append(шаг)
            continue
        было_статус = шаг["статус"]
        спрошено = шаг["спрошено"]
        цель = шаг["цель"]

        if было_статус == CONFIRMED:
            # Сегодняшняя дверь говорит «слово настоящее, чинить нечего». Именно так
            # закрылись «gehen», «vier», «wenn», «aber» — вчерашний приговор хотел
            # переписать их в «Gehen», «Vier», «Wenn», «Aber».
            шаг["действие"] = "дверь подтвердила слово — менять нечего"
            план.append(шаг)
            continue
        if было_статус == UNCONFIRMED:
            # Ни один справочник не подтвердил. Это не наше решение — очередь владельцу
            # уходит личкой с кнопками (backend/word_review.py), здесь не трогаем.
            шаг["действие"] = "не подтверждено — ждёт владельца"
            план.append(шаг)
            continue
        свой = _единица(cur, спрошено)
        карточек = _личных_карточек(cur, спрошено)
        в_пуле = _в_пуле(cur, спрошено)
        шаг.update({"единица": свой, "карточек": карточек, "в_пуле": в_пуле})

        if было_статус == NOT_A_WORD:
            if карточек:
                шаг["действие"] = "мусор, но лежит в личной карточке — ВЛАДЕЛЬЦУ"
            elif свой or в_пуле:
                шаг["действие"] = "снять из наших данных"
            else:
                шаг["действие"] = "нигде нет — применять не к чему"
            план.append(шаг)
            continue

        чужой = _единица(cur, цель) if цель else None
        if not (свой or в_пуле or карточек):
            шаг["действие"] = "нигде нет — применять не к чему"
        elif чужой and свой and чужой != свой:
            шаг["действие"] = "склейка с существующим словом"
            шаг["куда"] = чужой
        elif свой:
            шаг["действие"] = "переименование во всех хранилищах"
        else:
            # Своей строки словаря нет, а в пуле или карточках старый текст лежит.
            шаг["действие"] = "правка текста в пуле и карточках"
        план.append(шаг)
    return план


def применить(cur, шаг: dict) -> str:
    from backend.database import spread_correction_everywhere
    from backend.lex_units import merge_unit_into, retitle_unit

    действие = шаг["действие"]
    спрошено, цель = шаг["спрошено"], _цель(шаг)

    if действие == "дверь подтвердила слово — менять нечего":
        _отметить(cur, спрошено)
        return "слово настоящее, вчерашний приговор отменён"

    if действие == "не подтверждено — ждёт владельца":
        return "оставлено владельцу"

    if действие == "склейка с существующим словом":
        merge_unit_into(cur, int(шаг["единица"]), int(шаг["куда"]))
        spread_correction_everywhere(cur, unit_id=int(шаг["куда"]),
                                     old_text=спрошено, new_text=цель)
        добито = _добить_остатки(cur, спрошено, цель)
        _отметить(cur, спрошено, цель)
        return f"склеено с «{цель}»" + (f", добито {добито}" if добито else "")

    if действие == "переименование во всех хранилищах":
        retitle_unit(cur, int(шаг["единица"]), цель)
        spread_correction_everywhere(cur, unit_id=int(шаг["единица"]),
                                     old_text=спрошено, new_text=цель)
        добито = _добить_остатки(cur, спрошено, цель)
        _отметить(cur, спрошено, цель)
        return f"переименовано в «{цель}»" + (f", добито {добито}" if добито else "")

    if действие == "правка текста в пуле и карточках":
        # Своей строки словаря нет — развозить нечего от чьего-то имени, поэтому правим
        # адресно те два хранилища, где текст действительно лежит.
        сделано = _добить_остатки(cur, спрошено, цель)
        _отметить(cur, спрошено, цель)
        return f"поправлено записей: {сделано}"

    if действие == "снять из наших данных":
        cur.execute("DELETE FROM bt_3_dictionary_entries "
                    "WHERE lower(word_de)=lower(%s) OR lower(translation_de)=lower(%s);",
                    (спрошено, спрошено))
        убрано = cur.rowcount
        if шаг.get("единица"):
            _снять_строку(cur, int(шаг["единица"]))
        _отметить(cur, спрошено)
        return f"снято: строка словаря + записей пула {убрано}"

    if действие == "нигде нет — применять не к чему":
        _отметить(cur, спрошено)
        return "нечего применять, отмечено"

    return "оставлено владельцу"


def _цель(шаг: dict) -> str:
    return str(шаг.get("цель") or "").strip()


def _добить_остатки(cur, старое: str, новое: str) -> int:
    """Дочистить старое написание там, куда развозка правки НЕ достаёт.

    ЗАЧЕМ. `spread_correction_everywhere` ходит по связям: карточки берёт условием
    `lex_unit_id = <слово>`, а записи пула — только те, на которые ссылаются найденные
    карточки, и правит в них `source_text`. Значит мимо неё проходят:

        карточка человека, у которой связь со словом не проставлена (lex_unit_id пуст
        или указывает на другую строку) — а таких много, связь появилась позже данных;
        запись пула, найденная по `word_de` / `translation_de`, а не через карточку.

    Проверка ФАКТОМ после первого применения 25.08.2026 нашла ровно это: у «Erfolgen»,
    «umgeworfen», «verzockt» остался старый текст в личной карточке, у «Seifenblasen» и
    «Verdecken» — в записи пула. Скрипт при этом отчитался «применено»: он верил своему
    счётчику, а не базе.

    ⚠ РАВЕНСТВО ПОЛЯ, А НЕ ВХОЖДЕНИЕ. Меняем поле, только если оно РАВНО старому тексту
    целиком. Замена по вхождению переписала бы «Erfolgen» внутри чужой фразы и внутри
    примеров — то есть развезла бы порчу вместо правки.

    Возвращает число тронутых строк.
    """
    сделано = 0
    for таблица, колонки in (("bt_3_dictionary_entries", ("word_de", "translation_de")),
                             ("bt_3_webapp_dictionary_queries", ("word_de", "translation_de"))):
        for колонка in колонки:
            cur.execute(f"UPDATE {таблица} SET {колонка}=%s, updated_at=NOW() "
                        f"WHERE lower({колонка})=lower(%s);", (новое, старое))
            сделано += cur.rowcount
    return сделано


def _отметить(cur, спрошено: str, цель: str = "") -> None:
    """Отметить «доехало» — но только если база это ПОДТВЕРЖДАЕТ.

    Первая версия ставила отметку сразу после записи, по факту «запрос выполнился».
    Проверка 25.08.2026 показала, чего это стоит: пять слов были отмечены применёнными,
    а старое написание осталось — в личной карточке или в записи пула. Отметка на веру
    не отличается от отсутствия отметки: она лишь прячет незакрытую правку.

    Теперь спрашиваем базу: если старого текста больше нигде нет — отмечаем. Если
    остался, отметку НЕ ставим, и следующий заход возьмёт слово снова.
    """
    if цель and цель.lower() != спрошено.lower():
        осталось = (_единица(cur, спрошено) or 0) + _в_пуле(cur, спрошено) \
            + _личных_карточек(cur, спрошено)
        if осталось:
            logging.warning("применение приговоров: %r отмечать рано, старый текст ещё "
                            "лежит в %d местах", спрошено, осталось)
            return
    cur.execute("UPDATE bt_3_word_check SET applied_at=NOW() WHERE asked=%s;", (спрошено,))


def _снять_строку(cur, unit_id: int) -> None:
    """Снять строку словаря, у которой НЕТ настоящего слова-получателя.

    Переносить некуда — слова не существует. Поэтому зависимые строки снимаются, а не
    переезжают. Личные карточки сюда не попадают: шаг с карточками уходит владельцу и
    до этой функции не доходит (см. собрать_план).
    """
    for таблица, колонка in (("bt_3_lex_surfaces", "unit_id"),
                             ("bt_3_lex_unit_sources", "unit_id"),
                             ("bt_3_lex_senses", "unit_id"),
                             ("bt_3_phrase_check", "unit_id"),
                             ("bt_3_phrase_review", "unit_id")):
        cur.execute(f"DELETE FROM {таблица} WHERE {колонка}=%s;", (unit_id,))
    cur.execute("DELETE FROM bt_3_lex_links WHERE from_unit=%s OR to_unit=%s;",
                (unit_id, unit_id))
    cur.execute("UPDATE bt_3_webapp_dictionary_queries SET lex_unit_id=NULL "
                "WHERE lex_unit_id=%s;", (unit_id,))
    cur.execute("DELETE FROM bt_3_lex_units WHERE id=%s;", (unit_id,))




def apply_pending_verdicts(*, apply: bool = False, переспрашивать: bool = True,
                           печатать: bool = False) -> dict:
    """Довезти до данных все приговоры, которые ещё не доехали.

    Одна точка на два вызывающих: руки (scripts/word_gate_apply_verdicts.py) и ночной
    актёр. Разной логики применения быть не должно — цена расхождения тут потеря
    чьей-то карточки.

    `переспрашивать=False` только для быстрого показа состава: применять без переспроса
    нельзя, см. правило про ядовитые приговоры в шапке модуля.
    """
    from backend.german_word_gate import ensure_word_check_schema
    ensure_word_check_schema()

    приговоры = _неприменённые()
    шаги = переспросить(приговоры, переспрашивать=переспрашивать)
    with get_db_connection_context() as conn:
        conn.autocommit = True
        with conn.cursor() as cur:
            план = собрать_план(cur, шаги)

    по_действиям: dict[str, list[dict]] = {}
    for шаг in план:
        по_действиям.setdefault(шаг["действие"], []).append(шаг)

    if печатать:
        print(f"Неприменённых приговоров: {len(план)}\n")
        for действие, шаги_действия in sorted(по_действиям.items(), key=lambda x: -len(x[1])):
            print(f"  {len(шаги_действия):3}  {действие}")
            for шаг in шаги_действия:
                хвост = _цель(шаг) + ("   [" + шаг["переписан"] + "]" if шаг.get("переписан") else "")
                print(f"         {шаг['спрошено']!r:22} → {хвост!r}")

    отчёт = {"всего": len(план), "сделано": 0, "не удалось": 0,
             **{д: len(ш) for д, ш in по_действиям.items()}}
    if not apply or not переспрашивать:
        отчёт["режим"] = "показ" if apply else "сухой прогон"
        if печатать:
            print("\nЭто ПОКАЗ. Ничего не изменено." if not переспрашивать
                  else "\nЭто СУХОЙ ПРОГОН. Ничего не изменено. Применить: --apply")
        return отчёт

    for шаг in план:
        try:
            with get_db_connection_context() as conn:
                with conn.cursor() as cur:
                    итог = применить(cur, шаг)
                conn.commit()
            if печатать:
                print(f"  {шаг['спрошено']!r:22} {итог}")
            отчёт["сделано"] += 1
        except Exception as exc:
            # НЕ ГЛУШИМ. Приговор остаётся неприменённым (applied_at пуст), и следующий
            # прогон возьмёт его снова. Именно этой второй попытки и не хватало ночному
            # проходу: там сбой применения означал потерю правки навсегда и молча.
            отчёт["не удалось"] += 1
            logging.warning("применение приговоров: %r не применён: %s", шаг["спрошено"], exc)
            if печатать:
                print(f"  {шаг['спрошено']!r:22} НЕ ПРИМЕНЁН: {str(exc)[:90]}")

    # Проверка ФАКТОМ: спрашиваем базу заново, а не верим счётчику.
    with get_db_connection_context() as conn:
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute("""SELECT count(*) FROM bt_3_word_check
                            WHERE status IN ('исправлено','не слово') AND applied_at IS NULL;""")
            отчёт["осталось неприменённых"] = int(cur.fetchone()[0])
    if печатать:
        print(f"\nобработано: {отчёт['сделано']} · не удалось: {отчёт['не удалось']} · "
              f"осталось неприменённых: {отчёт['осталось неприменённых']}")
    return отчёт
