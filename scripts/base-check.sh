#!/bin/sh
# «Не устарела ли моя копия ИМЕННО ТАМ, где я работаю?»
#
# ┌─ ПРОВЕРЕНО 24.08.2026. НЕ ПОДНИМАТЬ «ОТСТАВАНИЕ» КАК НАХОДКУ. ─────────────────┐
# │ Главный каталог владельца ВСЕГДА отстаёт от refactor/interface, и это устройство │
# │ работы, а не дефект: `git worktree list` показывает 44 рабочих каталога, каждый  │
# │ агент вливает свою ветку в refactor/interface, Railway с неё же деплоит. Замер   │
# │ 24.08.2026: подтянулся, запушил — и через ОДНУ минуту снова отставал на коммит.  │
# │ Держать копию «ровно на сервере» физически невозможно и не нужно.                │
# │                                                                                 │
# │ Сырое число отставания НИ О ЧЁМ не говорит и владельцу не выносится. Дважды его  │
# │ выносили как находку («70 коммитов», «20 коммитов»), дважды оно оказывалось       │
# │ нормой, и оба раза стоило времени на опровержение.                               │
# │                                                                                 │
# │ Настоящая опасность узкая: померить или починить на устаревшей копии ТЕ ФАЙЛЫ,   │
# │ которые кто-то уже переписал на сервере. Ровно на этот вопрос отвечает скрипт.   │
# │ Перемерить: ./scripts/base-check.sh <пути>                                       │
# └─────────────────────────────────────────────────────────────────────────────────┘
#
#   ./scripts/base-check.sh                      # по файлам, которые уже правлю
#   ./scripts/base-check.sh backend/database.py  # по тем, которые СОБИРАЮСЬ трогать
#
# Коды выхода:  0 — работай;  1 — твои файлы переписаны, подтянись;  2 — не спросили сервер.

REMOTE=bot3_webapp
BRANCH=refactor/interface

REPO_ROOT=$(git rev-parse --show-toplevel) || exit 2
cd "$REPO_ROOT" || exit 2

# Сеть здесь регулярно капризничает: HTTP/2 к github.com виснет на 75 секунд (разобрано
# трассировкой 02.08.2026), поэтому HTTP/1.1 и жёсткий предел на «молчащее» соединение.
# Не спросили сервер — это НЕ «всё хорошо», это отдельный ответ, код 2.
if ! git -c http.version=HTTP/1.1 -c http.lowSpeedLimit=1000 -c http.lowSpeedTime=20 \
        fetch --quiet "$REMOTE" "$BRANCH" 2>/dev/null; then
    echo "⚠️  Не достучались до $REMOTE — свежесть копии НЕ проверена."
    echo "   Это не «всё в порядке». Повторите, когда будет связь: ./scripts/base-check.sh $*"
    exit 2
fi

BEHIND=$(git rev-list --count HEAD..FETCH_HEAD 2>/dev/null || echo 0)

if [ "$BEHIND" -eq 0 ]; then
    echo "✅ Копия ровно на сервере. Работай."
    exit 0
fi

# Что проверяем. Без аргументов — файлы, которые человек уже правит: именно их устаревшая
# база и портит. Правок нет и путей не назвали — сказать об этом прямо, а не молча
# отвечать «всё хорошо» на вопрос, которого не задавали.
if [ $# -gt 0 ]; then
    PATHS="$*"
    WHAT="Названные файлы"
else
    PATHS=$(git status --porcelain | awk '{ $1=""; sub(/^ +/,""); print }' | tr '\n' ' ')
    WHAT="Файлы, которые вы уже правите,"
fi

if [ -z "$PATHS" ]; then
    echo "ℹ️  Копия отстаёт на $BEHIND коммит(ов) — это НОРМА, в репозитории 40+ worktree."
    echo "   Проверять нечего: правок нет и пути не названы."
    echo "   Перед работой назовите их:  ./scripts/base-check.sh <пути, которые будете трогать>"
    exit 0
fi

# shellcheck disable=SC2086
TOUCHED=$(git log --oneline HEAD..FETCH_HEAD -- $PATHS 2>/dev/null)

if [ -z "$TOUCHED" ]; then
    echo "✅ Копия отстаёт на $BEHIND коммит(ов) — и это НОРМА (40+ worktree, все льют в $BRANCH)."
    echo "   $WHAT на сервере НИКТО не трогал. Замер и правка действительны, работай."
    echo "   Само число отставания — не находка, владельцу его не носить."
    exit 0
fi

echo "⛔️ СТОП. $WHAT переписаны на сервере — база устарела ИМЕННО ЗДЕСЬ."
echo ""
echo "$TOUCHED" | head -n 20
echo ""
# shellcheck disable=SC2086
git diff --stat HEAD FETCH_HEAD -- $PATHS | tail -n 20
echo ""
echo "   Мерить и править на этом нельзя — выводы будут про мёртвый код."
echo "   Подтянуться:  git -c http.version=HTTP/1.1 pull --rebase $REMOTE $BRANCH"
exit 1
