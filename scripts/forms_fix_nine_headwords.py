# -*- coding: utf-8 -*-
"""Починить девять записей, которым не досталось таблицы форм.

ОТКУДА ДЕВЯТЬ. 23.08.2026 из фронта убран счётчик, дорисовывавший таблицу, когда сервер
её не даёт. Без таблицы остались 34 слова. Прогрев справочником закрыл 25 из них —
у тех заголовок был целый, просто ночная порция (120 слов) до них не дошла. Осталось
девять, и у них заголовок или часть речи вправду негодны.

ПОЧЕМУ НЕЛЬЗЯ ПРОСТО СПРОСИТЬ ДВЕРЬ. Спросил — и она ответила ВЕРНО, но не на тот
вопрос:

    gehen  → «Gehen»  (существительное)   а карточка про ГЛАГОЛ «идти»
    wenn   → «Wenn»   (существительное)   а карточка про СОЮЗ «если»
    vier   → «Vier»   (существительное)   а карточка про ЧИСЛИТЕЛЬНОЕ «четыре»

Существительные «das Gehen», «das Wenn», «die Vier» вправду существуют, и справочник
честно их подтверждает. Но это ДРУГИЕ слова, не те, что сохранил человек. Источник прав,
вопрос был неверен.

ПОЭТОМУ У КАЖДОЙ ПРАВКИ НАЗВАН СВОЙ ИСТОЧНИК, и их три разных:

    разбор карточки      часть речи и перевод, собранные при разборе слова
    указатель форм       какая лемма у этой формы («erwartungen» → «Erwartung»)
    справочник           современное написание вместо дореформенного

Ничего не выведено «по общему правилу»: у каждой строки ниже написано, откуда взято.

ЗАПУСК:
    python3 scripts/forms_fix_nine_headwords.py           # показать
    python3 scripts/forms_fix_nine_headwords.py --apply   # применить
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# (id, что сейчас, новый заголовок или None, новая часть речи или None, источник решения)
ПРАВКИ = [
    # Часть речи неверна: в базе «существительное», а разбор карточки говорит иное.
    # Заголовок при этом ЦЕЛЫЙ и менять его не надо — надо перестать считать слово
    # существительным, тогда его подхватит прогрев глаголов.
    (15708, "gehen", None, "verb",
     "разбор карточки: part_of_speech=verb, перевод «идти»"),
    (41427, "schwimmen", None, "verb",
     "разбор карточки: part_of_speech=verb, перевод «плавать»"),
    (41221, "vier", None, "numeral",
     "разбор карточки: перевод «четыре» — числительное, не существительное"),
    (20972, "wenn", None, "conjunction",
     "разбор карточки: перевод «если» — союз, не существительное"),
    (10735, "zu spät kommen", None, "phrase",
     "это оборот из трёх слов, помеченный прилагательным; вид записи уже «оборот»"),

    # Заголовок — форма множественного числа. Правило владельца 18.08.2026:
    # заголовок = словарная форма. Лемму берём НЕ на глаз, а из указателя форм.
    (23525, "erwartungen", "Erwartung", None,
     "указатель форм: «erwartungen» — множественное от «Erwartung»"),
    (26326, "unstimmigkeiten", "Unstimmigkeit", None,
     "указатель форм: «unstimmigkeiten» — множественное от «Unstimmigkeit»"),
    (21023, "zustimmungen", "Zustimmung", None,
     "указатель форм: «zustimmungen» — множественное от «Zustimmung»"),

    # Дореформенное написание. Справочник сам указывает современное.
    (20925, "entschluß", "Entschluss", None,
     "справочник: страница помечена как устаревшее написание, современное — «Entschluss»"),

    # Обратный случай: помечены ГЛАГОЛАМИ, а разбор говорит «существительное» и даёт
    # перевод «отрыжка» / «продвижение». Это отглагольные существительные, заголовок с
    # артиклем у них верный — неверна часть речи, и у второго ещё строчная буква.
    (8974, "das Aufstoßen", None, "noun",
     "разбор карточки: part_of_speech=noun, перевод «отрыжка»"),
    (15702, "das vordringen", "das Vordringen", "noun",
     "разбор карточки: part_of_speech=noun, word_de=«das Vordringen», перевод «продвижение»"),
]


def main() -> int:
    apply = "--apply" in sys.argv
    from backend.database import get_db_connection_context
    from backend.lex_units import retitle_unit

    print(f"Записей к починке: {len(ПРАВКИ)}\n")
    print(f"{'id':>7}  {'сейчас':22} {'станет':22} {'часть речи':12} источник")
    for uid, было, заголовок, часть, источник in ПРАВКИ:
        print(f"{uid:7}  {было:22} {(заголовок or '— без изменений'):22} "
              f"{(часть or '—'):12} {источник}")
    if not apply:
        print("\nЭто показ. Чтобы применить — добавь --apply")
        return 0

    сделано = {"заголовок": 0, "часть речи": 0}
    for uid, было, заголовок, часть, _источник in ПРАВКИ:
        with get_db_connection_context() as conn:
            with conn.cursor() as cur:
                if заголовок:
                    # Через retitle_unit: она чистит вход, пересчитывает ключ поиска и
                    # ВИД ЗАПИСИ, и заводит старое написание в указатель — человек,
                    # запомнивший «erwartungen», продолжит находить слово.
                    retitle_unit(cur, uid, заголовок)
                    сделано["заголовок"] += 1
                if часть:
                    cur.execute("UPDATE bt_3_lex_units SET pos=%s, pos_source=%s, "
                                "updated_at=NOW() WHERE id=%s;",
                                (часть, "разбор карточки", uid))
                    сделано["часть речи"] += 1
            conn.commit()
    print(f"\nПоправлено заголовков: {сделано['заголовок']} · частей речи: {сделано['часть речи']}")

    # Проверка ФАКТОМ: спрашиваем базу заново.
    with get_db_connection_context() as conn:
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute("SELECT id, display, pos FROM bt_3_lex_units WHERE id = ANY(%s) ORDER BY id;",
                        ([p[0] for p in ПРАВКИ],))
            print("\nЧто теперь в базе:")
            for uid, disp, pos in cur.fetchall():
                print(f"   {uid:7} {disp:24} {pos}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
